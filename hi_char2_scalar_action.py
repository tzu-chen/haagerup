"""Compare the full scalar action on finite phase points with ray classes.

The input certificates have already passed all Q and C. This checks the
additional action, stabilizers, and Frobenius cycles, without assuming a
class-field parametrization. Requires Python and PARI/GP. Missing small
certificates can be generated by hi_char2_general_search.py.
"""

from collections import Counter
import json
from math import gcd
from pathlib import Path
import subprocess

from hi_char2_partial_completion import load_phases
from hi_char2_ray_count import COUNTS


GP = r'''
ray_action(n)={
 my(b=bnfinit(x^2-n*x-1,1),D0=b.disc,F=sqrtint((n^2+4)/D0),
 m,epsilon=quadunit(D0),w,v,rows=List(),divs,u,ff,h,local,H,r);
 if(bnfcertify(b)!=1,error("uncertified maximal class group"));
 if(F^2*D0!=n^2+4||gcd(F,n)!=1,error("incorrect conductor"));
 m=quadunitindex(D0,F);
 w=Mod(1-(n-F)/2,n)/F;
 v=Mod(component(epsilon,2),n)+component(epsilon,3)*w;
 if(znorder(v)!=m,error("wrong maximal unit image"));
 divs=divisors(F);
 for(j=1,#divs,
  ff=divs[j];u=quadunitindex(D0,ff);
  local=ff;forprime(p=2,ff,if(ff%p==0,local*=1-kronecker(D0,p)/p));
  h=b.no*local/u;H=vecsort(vector(m/u,a,lift(v^(u*(a-1)))));
  if(denominator(h)!=1||#Set(H)!=m/u,error("bad class or unit count"));
  r=1;while(!setsearch(H,lift(Mod(2,n)^r)),r++);
  listput(rows,[ff,h,H,r]);
 );
 print(Vec(rows));
};
'''


def arithmetic(n):
    result = subprocess.run(
        ['gp', '-q', '-f'], text=True, capture_output=True,
        input=GP + f'iferr(ray_action({n}),e,print(e);quit(1));\nquit;\n')
    if result.returncode or result.stderr:
        raise ArithmeticError(result.stdout + result.stderr)
    return json.loads(result.stdout)


def verify_order(n, directory):
    paths = sorted(directory.glob(f'hi_finite_field_{n}_char2_general_*.json'))
    if not paths:
        paths = sorted(directory.glob(f'hi_finite_field_{n}_char2_*.json'))
    if not paths:
        raise FileNotFoundError(f'No characteristic-two certificates at {n}')
    data = [json.loads(path.read_text()) for path in paths]
    assert all(entry[:4] == data[0][:4] for entry in data)
    points = set()
    for path in paths:
        phases, omega, multiply, power = load_phases(path)
        initial = point = tuple(phases)
        orbit = set()
        while point not in orbit:
            orbit.add(point)
            next_point = tuple(point[2*a % n] for a in range(n))
            assert next_point == tuple(power(x, 4) for x in point)
            point = next_point
        assert point == initial and not (orbit & points)
        points.update(orbit)
    assert len(points) == COUNTS[n]
    units = [a for a in range(1, n) if gcd(a, n) == 1]
    remaining = set(points)
    observed = Counter()
    frobenius = Counter()
    while remaining:
        point = min(remaining)
        images = {u: tuple(point[u*a % n] for a in range(n)) for u in units}
        orbit = set(images.values())
        stabilizer = tuple(u for u in units if images[u] == point)
        assert orbit <= remaining
        assert len(orbit)*len(stabilizer) == len(units)
        remaining -= orbit
        observed[stabilizer] += 1
        r = 1
        while pow(2, r, n) not in stabilizer:
            r += 1
        assert len(orbit) % r == 0
        frobenius[r] += len(orbit)//r
    expected = Counter()
    expected_frobenius = Counter()
    rows = arithmetic(n)
    for conductor, class_number, stabilizer, degree in rows:
        expected[tuple(stabilizer)] += class_number
        ray_degree = class_number*len(units)//len(stabilizer)
        assert ray_degree % degree == 0
        expected_frobenius[degree] += ray_degree//degree
    assert observed == expected, (n, observed, expected)
    assert frobenius == expected_frobenius
    print(f'EXACT SCALAR ACTION n={n}; canonical points={len(points)}; '
          f'unit-group orbits={sum(observed.values())}; '
          f'[stabilizer,multiplicity]={sorted(observed.items())}; '
          f'[F4 degree,field factors]={sorted(frobenius.items())}; '
          f'all ray-action comparisons passed', flush=True)


def main():
    directory = Path(__file__).resolve().parent / 'hi_finite_field_certificates'
    for n in COUNTS:
        verify_order(n, directory)
    for n in [39, 81, 6561]:
        print(f'ARITHMETIC ONLY n={n}; [conductor,class number,unit subgroup,'
              f'Frobenius order]={arithmetic(n)}; NO HI SOLUTION ASSERTED', flush=True)
    print('ALL FINITE SCALAR-ACTION COMPARISONS PASSED; no uniform parametrization is proved.')


if __name__ == '__main__':
    main()
