"""Construct and independently verify finite-field HI existence certificates.

A complete certificate in characteristic ell not dividing n*(n*n+4)
gives a characteristic-zero fusion category by the algebraic reconstruction
and categorical lifting argument in Section 58. Scalar H or a nonempty
quadratic quotient alone does not suffice: every cubic is checked here.

The --algebra-dir option reuses the finite-field row algebras generated by
hi_column_circuits.py --output. No characteristic-zero HI data are read.
The --verify option needs only a small JSON certificate and PARI/GP.
"""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile


VERIFY_GP = r"""
verify_certificate()={
my(n=data[1],q=data[2],f=Mod(1,data[2])*Polrev(data[3],t),z,d,R,P,B,Q,C);
if(n<3||n%2==0||!isprime(q),error("invalid order or characteristic"));
if((n*(n^2+4))%q==0,error("degenerate global dimension"));
if(poldegree(f)<1||!polisirreducible(f),error("not a finite field"));
z=ffgen(f,'z);d=subst(Polrev(data[4],t),t,z);
if(d^2-n*d-1||d==0||d==1,error("invalid dimension"));
if(n*(1+d^2)==0,error("zero global dimension"));
if(#data[5]!=n,error("wrong row length"));
R=vector(n,a,subst(Polrev(data[5][a],t),t,z));
if(R[1]!=-1||R[2]!=-1,error("wrong exceptional row values"));
for(a=2,n-1,if(R[a+1]==0||R[a+1]!=R[n+2-a],error("row reflection or unit failure")));
P=vector(n,a,z^0);for(a=2,n-1,P[a+1]=P[a]*R[a+1]);
B=matrix(n,n,g,h,if(g==1&&h==1,d-2,if(g==1||h==1||g==h,-1,
  if(g<h,P[h]/(P[g]*P[h-g+1]),d*P[h]*P[g-h+1]/P[g]))));
for(g=0,n-1,for(h=0,n-1,
 if(B[g+1,h+1]!=B[(-h)%n+1,(g-h)%n+1],error("order-three symmetry"));
 Q=sum(a=0,n-1,B[(g+a)%n+1,h+1]*B[h+1,a+1])-(d-1)^2*((g==0)-(h==0)/d);
 if(Q,error("quadratic failure",[g,h]));
));
if(sum(a=1,n,B[a,1])/(d-1)!=-1/d,error("linear row-sum failure"));
for(g=0,n-1,for(h=0,n-1,for(k=0,n-1,for(l=0,n-1,
 C=sum(a=0,n-1,B[a+1,(g+h)%n+1]*B[g+1,(a+k)%n+1]*B[h+1,(a+l)%n+1]);
 C-=(d-1)*B[(g+l)%n+1,k+1]*B[(h+k)%n+1,l+1];
 C+=(d-1)^3/d*(g==0&&h==0);
 if(C,error("cubic failure",[g,h,k,l]));
))));
print("EXACT FINITE-FIELD HI CERTIFICATE: n=",n," characteristic=",q,
      " field degree=",poldegree(f),"; all ",n^2," Q and ",n^4," C passed; nonzero global dimension");
};
iferr(verify_certificate(),e,print(e);quit(1));
quit;
"""


def gp(source, directory, name):
    path = directory / (name + '.gp')
    path.write_text('default(parisizemax,1000000000);\n' + source)
    result = subprocess.run(['gp', '-q', '-f', str(path)], capture_output=True,
                            text=True, timeout=600)
    output = result.stdout + result.stderr
    if result.returncode or '***   at' in output:
        raise ArithmeticError(output)
    return output


def verify(path, directory):
    data = json.loads(path.read_text())
    if not isinstance(data, list) or len(data) != 5:
        raise ValueError('Certificate must contain n, characteristic, modulus, dimension, row')

    def integers(value):
        return type(value) is int or isinstance(value, list) and all(map(integers, value))

    if not integers(data):
        raise ValueError('Certificate contains noninteger data')
    result = gp('data=' + json.dumps(data) + ';\n' + VERIFY_GP, directory, 'verify')
    if 'EXACT FINITE-FIELD HI CERTIFICATE:' not in result:
        raise ArithmeticError(result)
    print(result, end='', flush=True)


def export_algebra(n, algebra, output, directory):
    from hi_column_circuits import SCALAR_GP
    prefix = algebra.read_text().split('BfromP(', 1)[0]
    if f'n={n};' not in prefix:
        raise ValueError('Algebra file has the wrong order')
    stem = output / f'hi_finite_field_{n}'
    filename = json.dumps(str(stem))
    save = r"""
  my(fc=vector(poldegree(ff[i,1])+1,j,lift(polcoef(ff[i,1],j-1))),rc);
  rc=vector(n,a,my(t0=rr[a]%ff[i,1]);vector(poldegree(ff[i,1]),j,lift(polcoef(t0,j-1))));
  write(Str(STEM,"_",i,".json"),[n,q,fc,[lift(d)],rc]);
""".replace('STEM', filename)
    source = SCALAR_GP.replace('qlength+=poldegree(ff[i,1])*degree;',
                              'qlength+=poldegree(ff[i,1])*degree;' + save)
    # These files belong to this invocation; GP write() appends to existing files.
    for path in output.glob(f'hi_finite_field_{n}_*.json'):
        path.unlink()
    result = gp(prefix+source, directory, 'export')
    if 'FINITE-FIELD SCALAR CHECK PASSED' not in result:
        raise ArithmeticError(result)
    paths = sorted(output.glob(f'hi_finite_field_{n}_*.json'))
    if not paths:
        raise ArithmeticError('The scalar filter supplied no candidates')
    return paths


def characteristic_two_examples(output):
    # F16 = F2[t]/(t^4+t+1). These are explicit small candidates, not a family.
    def mul(a, b):
        value = 0
        while b:
            if b & 1:
                value ^= a
            a <<= 1
            if a & 16:
                a ^= 19
            b >>= 1
        return value

    inverse = [0] + [next(b for b in range(1, 16) if mul(a, b) == 1) for a in range(1, 16)]
    coefficients = lambda a: [(int(a) >> j) & 1 for j in range(4)]
    paths = []
    for n, first, second in [(3, 11, 13), (11, 2, 3)]:
        residues = {a*a % n for a in range(1, n)}
        w = [1] + [first if a in residues else second for a in range(1, n)]
        row = [1, 1] + [mul(mul(w[1], w[a-1]), inverse[w[a]]) for a in range(2, n)]
        data = [n, 2, [1, 1, 0, 0, 1], coefficients(6), list(map(coefficients, row))]
        path = output / f'hi_finite_field_{n}_char2.json'
        path.write_text(json.dumps(data) + '\n')
        paths.append(path)
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--orders', type=int, nargs='+', default=[3, 5, 7, 11, 13])
    parser.add_argument('--algebra-dir', type=Path)
    parser.add_argument('--output', type=Path, default=Path('/tmp/hi_finite_field_certificates'))
    parser.add_argument('--verify', type=Path, nargs='+')
    parser.add_argument('--characteristic-two', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='hi_finite_field_') as temp:
        directory = Path(temp)
        if args.verify:
            paths = args.verify
        else:
            args.output.mkdir(parents=True, exist_ok=True)
            if args.characteristic_two:
                paths = characteristic_two_examples(args.output)
            else:
                paths = []
                for n in args.orders:
                    if args.algebra_dir is None:
                        from hi_column_circuits import construct, krylov_source
                        q, d, row, *_ = construct(n)
                        algebra = directory / f'upper{n}.gp'
                        algebra.write_text(krylov_source(n, q, d, row))
                    else:
                        algebra = args.algebra_dir / f'upper{n}.gp'
                    paths.extend(export_algebra(n, algebra, args.output, directory))
        for path in paths:
            verify(path, directory)
    print('ALL REQUESTED COMPLETE FINITE-FIELD CERTIFICATES PASSED')


if __name__ == '__main__':
    main()
