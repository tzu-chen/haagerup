#!/usr/bin/env python3
"""Lean text for the closure half of the minimal-generation record: S2 is closed under the five
operators and contains the 44 initial vectors (Benchmark.md section 5, "the remaining 524
closure relations").

Pure text processing of s2.json (json + fractions); it computes no modes (the kernel does).

    python3 lean/tools/lattice_export/gen_s2close.py [<budget ms per file>]

writes, in lean/HaagerupIzumi/C8/Lattice/,
    S2Close<NN>.lean   the 524 relations of s2.json that create no basis vector,
                       `source = sum c_i r_k_i`, one `decide +kernel` theorem `s2rel_<idx>` each,
                       packed by a cost model fitted to the measured S2Rel files
                       (ms per term of r_k: E_L, F_L 11; E_R, F_R 51; u_(1) 80);
    S2CloseMem.lean    `s2r_mem_k : r_k ∈ s2basis` and, for each of the 644 relations,
                       `s2src_mem_<idx> : toV4 source ∈ S2span`;
and prints the per-file estimates.  The hand-written S2Closure.lean assembles them.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402  (loads s2.json; helpers only)

R = g.DATA['relations']
B = g.DATA['basis']
MS_PER_TERM = [11, 11, 51, 51, 80]


def cost_ms(r):
    rhs = sum(len(B[k]) for k, _ in r['coeffs'])
    if r['source'][0] == 'op':
        return MS_PER_TERM[r['source'][1]] * len(B[r['source'][2]]) + rhs + 30
    return 120 + rhs


def memlist(coeffs):
    out = 'fun _ h => absurd h List.not_mem_nil'
    for k, _ in reversed(coeffs):
        out = f'List.forall_mem_cons.2 ⟨s2r_mem_{k}, {out}⟩'
    return f'({out})'


def write_close(budget):
    items = [(idx, r) for idx, r in enumerate(R) if r['new'] is None]
    files, cur, acc = [], [], 0.0
    for idx, r in items:
        c = cost_ms(r)
        if cur and acc + c > budget:
            files.append((cur, acc))
            cur, acc = [], 0.0
        cur.append((idx, r))
        acc += c
    files.append((cur, acc))
    for n, (group, acc) in enumerate(files):
        lines = [g.HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.S2Data')]
        lines.append(f'''/-!
# Closure relations of the minimal-generation record, part {n}

Generated by `lean/tools/lattice_export/gen_s2close.py` from `s2.json`.  Each `s2rel_i` is a
relation of the record that creates no new basis vector: the source (an initial vector or an
operator `E_L(0), F_L(0), E_R(0), F_R(0), u(1)` applied to a basis vector `r_k`, *computed* here
with the lattice modes) equals `∑ cᵢ r_kᵢ`, checked by kernel evaluation.  Estimated kernel time
of this file: about {acc / 1000:.1f} s.  Used in `S2CloseMem.lean`.
-/
''')
        lines.append(g.NS_OPEN)
        lines.append('set_option profiler true\nset_option profiler.threshold 50\n'
                     'set_option Elab.async false\n')
        for idx, r in group:
            lines.append(g.rel_theorem(idx, r))
        lines.append(g.NS_CLOSE)
        (g.LEAN / f'S2Close{n:02d}.lean').write_text('\n'.join(lines))
    return files


def write_mem(nfiles):
    imports = ['public import HaagerupIzumi.C8.Lattice.S2Link']
    imports += [f'public import HaagerupIzumi.C8.Lattice.S2Close{n:02d}' for n in range(nfiles)]
    lines = [g.HEADER.format(imports='\n'.join(imports))]
    lines.append('''/-!
# Every source vector of the minimal-generation record lies in `S₂` (generated proofs)

Generated by `lean/tools/lattice_export/gen_s2close.py`.  `s2src_mem_i`: the source of relation
`i` of the record (`S2Rel*.lean`: relations creating a basis vector; `S2Close*.lean`: all others)
lies in `S2span`, because it equals a combination of basis vectors.  Assembled in
`S2Closure.lean`.
-/
''')
    lines.append(g.NS_OPEN)
    lines.append('''theorem rel_mem_combo {src : Vec4} {cs : List (QA × Vec4)} (h : src = combo cs)
    (hcs : ∀ p ∈ cs, p.2 ∈ s2basis) : toV4 src ∈ S2span := by
  rw [h]
  exact toV4_combo_mem cs fun p hp => s2basis_mem_span _ (hcs p hp)

theorem rel_mem_new {src r : Vec4} {s : QA} {cs : List (QA × Vec4)}
    (h : src = Vec4.add (Vec4.smulQA s r) (combo cs)) (hr : r ∈ s2basis)
    (hcs : ∀ p ∈ cs, p.2 ∈ s2basis) : toV4 src ∈ S2span :=
  src_mem_of_rel h (s2basis_mem_span _ hr) fun p hp => s2basis_mem_span _ (hcs p hp)
''')
    for k in range(len(B)):
        lines.append(f'theorem s2r_mem_{k} : s2r_{k} ∈ s2basis := by simp [s2basis]\n')
    for idx, r in enumerate(R):
        src = g.source_term(r['source'])
        if r['new'] is None:
            proof = f'rel_mem_combo s2rel_{idx} {memlist(r["coeffs"])}'
        else:
            proof = f'rel_mem_new s2rel_{idx} s2r_mem_{r["new"]} {memlist(r["coeffs"])}'
        lines.append(f'theorem s2src_mem_{idx} : toV4 ({src}) ∈ S2span :=\n  {proof}\n')
    lines.append(g.NS_CLOSE)
    (g.LEAN / 'S2CloseMem.lean').write_text('\n'.join(lines))


def main():
    budget = float(sys.argv[1]) if len(sys.argv) > 1 else 2500.0
    files = write_close(budget)
    write_mem(len(files))
    ests = [round(a / 1000, 2) for _, a in files]
    print(json.dumps({'files': len(files), 'relations': sum(len(f) for f, _ in files),
                      'total_est_s': round(sum(ests), 1), 'max_est_s': max(ests),
                      'checks': [len(f) for f, _ in files]}))


if __name__ == '__main__':
    main()
