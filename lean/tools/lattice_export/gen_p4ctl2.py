#!/usr/bin/env python3
"""Lean replay of a right-current control of the triplet, merge by output-state ranges
(generalization of gen_p4ctl_fRqp.py, which did fR_qp).  Pure text processing.

    python3 lean/tools/lattice_export/gen_p4ctl2.py <control> [<pieces>]

controls: fR_q0 (F_R(0) q0 = q-), fR_qm (F_R(0) q- = 0), eR_qp (E_R(0) q+ = 0).
Uses from gen_p4ctl.py (moved from drafts/p4ctl into the tree by the build script): sub-chunk
inputs P4Sub<F>*, images P4Img<C>*, per-sub-chunk checks P4Chk<C>*.  Writes:
    P4SubLk<F><c><x>.lean, P4SubLk<F><c>.lean   sub-chunk links by component (not for F = P: built)
    P4Ip<C><n>.lean, P4Il<C><n>.lean            image pieces and their links
    P4Ep<C><n>.lean, P4El<C><x>.lean            pieces of the expected vector (fR_q0 only)
    P4Mg<C><k>.lean                             merge pieces (= expected piece, or Vec4.zero)
    P4R<C>.lean                                 the identity in V and the LowerCertificate field
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402
import p4_chunks  # noqa: E402

BUDGET = 25000
SPEC = {  # control: (input id, F, expected id or None, current, tag C, D-field, expected D-field)
    'fR_q0': ('P4_zero', 'Z', 'P4_minus', 'fR', 'FRZ', 'q0', 'qm'),
    'fR_qm': ('P4_minus', 'M', None, 'fR', 'FRM', 'qm', None),
    'eR_qp': ('P4_plus', 'P', None, 'eR', 'ERP', 'qp', None),
}
VNAME = {'P': 'qpV', 'Z': 'q0V', 'M': 'qmV'}
FLETTER = {'P4_plus': 'P', 'P4_zero': 'Z', 'P4_minus': 'M'}
PROF = 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'


def key(t):
    return (tuple(t[0]), tuple(t[1]))


def lit_vec(v):
    return sum(10 + len(o) for m, o, cs in v for x in cs if Fraction(x) != 0) + 40


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_p4ctl2.py`.  {body}\n-/\n'
            + g.NS_OPEN)


def pack(items, size):
    files, cur, acc = [], [], 0
    for it in items:
        n = size(it)
        if cur and acc + n > BUDGET:
            files.append(cur)
            cur, acc = [], 0
        cur.append(it)
        acc += n
    if cur:
        files.append(cur)
    return files


def split(v, bounds):
    pieces = [[] for _ in range(len(bounds) + 1)]
    for t in sorted(v, key=key):
        k = sum(1 for b in bounds if b <= key(t))
        pieces[k].append(t)
    return pieces


def lsum(terms):
    return ' + '.join(terms)


def main():
    ctl = sys.argv[1]
    K = int(sys.argv[2]) if len(sys.argv) > 2 else 12
    inp, F, exp, cur, C, qd, ed = SPEC[ctl]
    out = g.LEAN
    lines = (HERE / 'p4_controls' / f'{ctl}.jsonl').read_text().splitlines()
    meta = json.loads(lines[0])
    recs = [json.loads(x) for x in lines[1:-1]]
    N = len(recs)
    P4 = json.loads((HERE / 'p4.json').read_text())
    fields = {f['id']: f['vector'] for f in P4['fields']}
    subs = p4_chunks.control_subchunks(fields[inp], ctl, meta['states_per_chunk'])
    assert len(subs) == N
    if exp:
        ref = sorted(fields[exp], key=key)
    else:
        ref = sorted({key(t) for r in recs for t in r['image']})
        ref = [[list(a), list(o)] for a, o in ref]
    step = (len(ref) + K - 1) // K
    bounds = [key(ref[i]) for i in range(step, len(ref), step)][:K - 1]
    K = len(bounds) + 1
    sname = lambda c, j: f'p4s{F}_{c}_{j}'  # noqa: E731
    subfile = {}
    for f in sorted(out.glob(f'P4Sub{F}[0-9]*.lean')):
        for line in f.read_text().splitlines():
            if line.startswith(f'noncomputable def p4s{F}_'):
                subfile[line.split()[2]] = f.stem
    imgfile = {}
    for f in sorted(out.glob(f'P4Img{C}*.lean')):
        for line in f.read_text().splitlines():
            if line.startswith(f'noncomputable def p4i_{ctl}_'):
                imgfile[int(line.split()[2].rsplit('_', 1)[1])] = f.stem
    nchunks = 1 + max(c for c, _, _ in subs)
    files = {'links': [], 'ip': [], 'il': [], 'ep': [], 'el': [], 'mg': [], 'r': []}

    # 1. sub-chunk links by component (field P is built)
    if F != 'P':
        for c in range(nchunks):
            js = [j for cc, j, _ in subs if cc == c]
            lst = ', '.join(sname(c, j) for j in js)
            imps = ['P4Ctl', f'P4Data{F}{c}'] + sorted({subfile[sname(c, j)] for j in js})
            for x in range(4):
                text = header(imps, f'Triplet `{inp}`, chunk {c}, component c{x}: the sub-chunks add up to the data',
                              'Kernel check of one component of the link.')
                text += PROF
                text += (f'\ntheorem p4s{F}_{c}_link_c{x} :\n    (nz4 (sort4 (toVec4Q [{lst}].flatten))).c{x} =\n'
                         f'      p4{F}_{c}.c{x} := by\n  decide +kernel\n')
                text += g.NS_CLOSE
                (out / f'P4SubLk{F}{c}{x}.lean').write_text(text)
                files['links'].append(f'P4SubLk{F}{c}{x}')
            text = header(['P4Ctl2'] + [f'P4SubLk{F}{c}{x}' for x in range(4)],
                          f'Triplet `{inp}`, chunk {c}: the sub-chunks add up to the data', 'Assembled by `vec4_ext`.')
            text += (f'\ntheorem p4s{F}_{c}_link :\n    nz4 (sort4 (toVec4Q [{lst}].flatten)) = p4{F}_{c} :=\n'
                     f'  vec4_ext p4s{F}_{c}_link_c0 p4s{F}_{c}_link_c1 p4s{F}_{c}_link_c2 p4s{F}_{c}_link_c3\n')
            text += g.NS_CLOSE
            (out / f'P4SubLk{F}{c}.lean').write_text(text)
            files['links'].append(f'P4SubLk{F}{c}')

    # 2. image pieces
    ip = lambda i, k: f'p4ip_{ctl}_{i}_{k}'  # noqa: E731
    items = [(i, k, piece) for i, r in enumerate(recs) for k, piece in enumerate(split(r['image'], bounds))]
    ipfile_of = {}
    for n, group in enumerate(pack(items, lambda t: lit_vec(t[2]))):
        text = header(['QA'], f'Control `{ctl}`: pieces of the partial images, part {n}',
                      'Data: the terms of each image in each range of output states.')
        for i, k, piece in group:
            ipfile_of[(i, k)] = f'P4Ip{C}{n}'
            text += f'\nnoncomputable def {ip(i, k)} : Vec4 :=\n  {g.vec4(piece)}\n'
        text += g.NS_CLOSE
        (out / f'P4Ip{C}{n}.lean').write_text(text)
        files['ip'].append(f'P4Ip{C}{n}')
    il_groups = [list(range(a, min(a + 6, N))) for a in range(0, N, 6)]
    for n, group in enumerate(il_groups):
        imps = ['P4Ctl2'] + sorted({imgfile[i] for i in group} | {ipfile_of[(i, k)] for i in group for k in range(K)})
        text = header(imps, f'Control `{ctl}`: images are the concatenations of their pieces, part {n}', 'Kernel check.')
        text += PROF
        for i in group:
            text += (f'\ntheorem p4il_{ctl}_{i} : cat4 [{", ".join(ip(i, k) for k in range(K))}] = p4i_{ctl}_{i} := by\n'
                     '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4Il{C}{n}.lean').write_text(text)
        files['il'].append(f'P4Il{C}{n}')

    # 3. expected pieces
    ep = lambda k: f'p4ep_{ctl}_{k}'  # noqa: E731
    EF = FLETTER[exp] if exp else None
    epfile_of = {}
    if exp:
        for n, group in enumerate(pack(list(enumerate(split(fields[exp], bounds))), lambda t: lit_vec(t[1]))):
            text = header(['QA'], f'Control `{ctl}`: pieces of the expected vector, part {n}',
                          f'Data: the terms of `{exp}` in each range of states.')
            for k, piece in group:
                epfile_of[k] = f'P4Ep{C}{n}'
                text += f'\nnoncomputable def {ep(k)} : Vec4 :=\n  {g.vec4(piece)}\n'
            text += g.NS_CLOSE
            (out / f'P4Ep{C}{n}.lean').write_text(text)
            files['ep'].append(f'P4Ep{C}{n}')
        eps = ', '.join(ep(k) for k in range(K))
        for x in range(4):
            imps = ['P4Ctl2'] + sorted(set(epfile_of.values())) + [f'P4Data{EF}{c}' for c in range(4)]
            text = header(imps, f'The expected vector is the concatenation of its pieces, component c{x}', 'Kernel check.')
            text += PROF
            text += (f'\ntheorem p4el_{ctl}_c{x} : (cat4 [{eps}]).c{x} = (cat4 [p4{EF}_0, p4{EF}_1, p4{EF}_2, p4{EF}_3]).c{x} := by\n'
                     '  decide +kernel\n')
            text += g.NS_CLOSE
            (out / f'P4El{C}{x}.lean').write_text(text)
            files['el'].append(f'P4El{C}{x}')

    # 4. merge pieces
    for k in range(K):
        imps = ['P4Ctl2'] + ([epfile_of[k]] if exp else []) + sorted({ipfile_of[(i, k)] for i in range(N)})
        text = header(imps, f'Control `{ctl}`: merge check, output range {k}',
                      'The pieces of the partial images in this range add up to the expected piece.')
        text += PROF
        rhs = ep(k) if exp else 'Vec4.zero'
        text += (f'\ntheorem p4mg_{ctl}_{k} :\n    sum4 [{", ".join(ip(i, k) for i in range(N))}] =\n'
                 f'      {rhs} := by\n  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4Mg{C}{k}.lean').write_text(text)
        files['mg'].append(f'P4Mg{C}{k}')

    # 5. assembly
    imps = (['P4Link', 'P4Ctl2'] + [f'P4SubLk{F}{c}' for c in range(nchunks)]
            + [f'P4Chk{C}{i:02d}' for i in range(N)] + files['il'] + files['el'] + files['mg'])
    qv = VNAME[F]
    expV = VNAME[EF] if exp else '0'
    text = header(imps, f'Control `{ctl}` for the actual triplet',
                  f'`{cur}_(0) {qv} = {expV}` from the per-sub-chunk checks `P4Chk{C}*` (`modeQRF`), the links '
                  f'`P4SubLk{F}*`, the image pieces `P4Il{C}*` and the merge pieces `P4Mg{C}*`; hence the '
                  f'`LowerCertificate` field `{ctl}` for `latticeDP`.  No hypotheses beyond `FLMInput`.')
    pairs = ', '.join(f'({sname(c, j)}, p4i_{ctl}_{i})' for i, (c, j, _) in enumerate(subs))
    text += f'\nnoncomputable def p4pairs_{ctl} : List (QVec × Vec4) :=\n  [{pairs}]\n'
    alt = ' | '.join(['rfl'] * N)
    checks = ', '.join(f'p4c_{ctl}_{i}' for i in range(N))
    links = ', '.join(f'toV4_eq_of_link p4s{F}_{c}_link' for c in range(nchunks))
    SL = 'simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]'
    ehave = '\n'.join(
        f'    have e{i} : toV4 p4i_{ctl}_{i} = {lsum(f"toV4 {ip(i, k)}" for k in range(K))} := by\n'
        f'      rw [← p4il_{ctl}_{i}, toV4_cat4]\n      {SL}\n      abel' for i in range(N))
    text += f'''
theorem p4pairs_{ctl}_ok : ∀ p ∈ p4pairs_{ctl},
    (∀ q ∈ p.1, Valid q.1) ∧ nz4 (sort4 (toVec4Q (modeQRF {cur} 0 p.1))) = p.2 := by
  intro p hp
  simp only [p4pairs_{ctl}, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with {alt}
  exacts [{checks}]
'''
    if exp:
        mhave = '\n'.join(
            f'    have m{k} : toV4 {ep(k)} = {lsum(f"toV4 {ip(i, k)}" for i in range(N))} := by\n'
            f'      rw [← p4mg_{ctl}_{k}, toV4_sum4]\n      {SL}\n      abel' for k in range(K))
        text += f'''
set_option maxHeartbeats 1000000 in
theorem {expV}_pieces_{ctl} : {expV} = {lsum(f"toV4 {ep(k)}" for k in range(K))} := by
  have h : cat4 [{eps}] = cat4 [p4{EF}_0, p4{EF}_1, p4{EF}_2, p4{EF}_3] :=
    vec4_ext p4el_{ctl}_c0 p4el_{ctl}_c1 p4el_{ctl}_c2 p4el_{ctl}_c3
  have h2 := congrArg toV4 h
  rw [toV4_cat4, toV4_cat4] at h2
  {SL} at h2
  simp only [{expV}, p4{EF}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]
  rw [← h2]
  abel
'''
        final = (f'    {SL}\n    rw [{", ".join(f"e{i}" for i in range(N))}, {expV}_pieces_{ctl}, '
                 f'{", ".join(f"m{k}" for k in range(K))}]\n    abel')
    else:
        mhave = '\n'.join(
            f'    have m{k} : {lsum(f"toV4 {ip(i, k)}" for i in range(N))} = 0 := by\n'
            f'      have h := congrArg toV4 p4mg_{ctl}_{k}\n      rw [toV4_sum4, toV4_zero] at h\n'
            f'      {SL} at h\n      rw [← h]\n      abel' for k in range(K))
        # (4 Oct 2026, 16:20) the earlier `rw [hg, ...]` with a flat left-nested `hg` could not
        # match the goal (right-nested over images); prove `grouped = 0` and close by `abel`.
        grouped = lsum(f'({lsum(f"toV4 {ip(i, k)}" for i in range(N))})' for k in range(K))
        final = (f'    {SL}\n    rw [{", ".join(f"e{i}" for i in range(N))}]\n'
                 f'    have hz : {grouped} = 0 := by\n'
                 f'      rw [{", ".join(f"m{k}" for k in range(K))}]\n      all_goals simp\n'
                 f'    refine Eq.trans ?_ hz\n    abel')
    dexp = f'(latticeDP hF S₃ hS₃).{ed}' if exp else '0'
    text += f'''
set_option maxHeartbeats 1000000 in
/-- **`{cur}(0) {qv} = {expV}`** in `V`. -/
theorem {ctl}V : modeC 0 (toV {cur}) {qv} = {expV} := by
  have h := ctl_pairs {cur} {cur}_valid 0 p4pairs_{ctl} p4pairs_{ctl}_ok
  have hin : {qv} = (p4pairs_{ctl}.map fun p => toVQ p.1).sum := by
    simp only [{qv}, p4{F}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    rw [{links}]
    simp only [p4pairs_{ctl}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    abel
  have hout : (p4pairs_{ctl}.map fun p => toV4 p.2).sum = {expV} := by
{ehave}
{mhave}
    simp only [p4pairs_{ctl}]
{final}
  rw [hin, h, hout]

/-- **Control `{ctl}`** of `LowerCertificate` for the actual triplet. -/
theorem {ctl}_latticeDP (hF : FLMInput) (S₃ : Submodule ℂ V) (hS₃ : S₃ ≤ gradeC 3) :
    (latticeVOA hF).mode 0 (latticeDP hF S₃ hS₃).{cur} (latticeDP hF S₃ hS₃).{qd} = {dexp} :=
  {ctl}V

#print axioms {ctl}_latticeDP
'''
    text += g.NS_CLOSE
    (out / f'P4R{C}.lean').write_text(text)
    files['r'].append(f'P4R{C}')
    data = [f'P4Sub{F}{n}' for n in (0, 1)] if F != 'P' else []
    data += sorted(set(imgfile.values()), key=lambda s: int(s[len(f'P4Img{C}'):])) + files['ip'] + files['ep']
    order = data + files['links'] + files['il'] + files['el'] + files['mg'] + [f'P4Chk{C}{i:02d}' for i in range(N)] + files['r']
    print(' '.join(order))


if __name__ == '__main__':
    main()
