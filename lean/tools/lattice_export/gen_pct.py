#!/usr/bin/env python3
"""Convert pct.json (export_pct.py) into Lean kernel checks of the PCT certificate theta_g S2 = S2.

Pure text processing (json + fractions); no lattice arithmetic, no modes.

    python3 lean/tools/lattice_export/gen_pct.py probe
        writes lean/tools/lattice_export/drafts/PCTProbe.lean (the costliest check alone)
    python3 lean/tools/lattice_export/gen_pct.py files <ms per unit> [<budget ms per file>]
        writes lean/HaagerupIzumi/C8/Lattice/PCTRel<NN>.lean

Each check is `sort4 (pct4 r_k) = combo [(c_j, r_j), ...]` (`Lattice/PCTCore.lean`): theta_g
applied to the basis vector r_k of S2Data.lean, re-sorted, equals the combination read from
pct.json; one more check for theta_g u.  The cost proxy of a check is
2 |r_k| + 4 sum_j |r_j| (terms over all four components); the files are packed to the given
budget with the measured milliseconds per unit.
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[1] / 'HaagerupIzumi' / 'C8' / 'Lattice'
PCT = json.loads((HERE / 'pct.json').read_text())
S2 = json.loads((HERE / 's2.json').read_text())
SIZE = [sum(sum(1 for x in cs if Fraction(x) != 0) for _, _, cs in r) for r in S2['basis']]
U_SIZE = sum(sum(1 for x in cs if Fraction(x) != 0) for _, _, cs in S2['u'])


def zz(n):
    return 2 * n if n >= 0 else -2 * n - 1


def qa(cs):
    fs = [Fraction(x) for x in cs]
    return 'decQA [' + ', '.join(f'{zz(f.numerator)}, {f.denominator}' for f in fs) + ']'


def checks():
    out = [(f's2r_{im["k"]}', f'pct_rel_{im["k"]}', im['coeffs'], SIZE[im['k']])
           for im in PCT['images']]
    out.append(('s2u', 'pct_rel_u', PCT['u_image'], U_SIZE))
    return out


def cost(c):
    return 2 * c[3] + 4 * sum(SIZE[j] for j, _ in c[2])


def theorem(c):
    src, name, coeffs, _ = c
    combo = ', '.join(f'({qa(cs)}, s2r_{j})' for j, cs in coeffs)
    return (f'/-- `θ_g {src} = ∑ cⱼ rⱼ` (`pct.json`). -/\n'
            f'theorem {name} :\n    sort4 (pct4 {src}) =\n      combo [{combo}] := by\n'
            f'  decide +kernel\n')


HEADER = '''module

public import HaagerupIzumi.C8.Lattice.S2Data
public import HaagerupIzumi.C8.Lattice.PCTCore

@[expose] public section

/-!
# {title}

Generated by `lean/tools/lattice_export/gen_pct.py` from `pct.json` (`export_pct.py`).  Each
`pct_rel_k` checks by kernel evaluation that the transported PCT involution `θ_g`
(`PCTCore.lean`, manuscript `eq:pct`) maps the basis vector `r_k` of `S₂` (`S2Data.lean`) to the
combination `∑ cⱼ rⱼ` recorded in `pct.json` (`pct_rel_u`: the same for `u`).  Estimated kernel
time of this file: about {secs} s.  Used in `PCTLink.lean`.
-/


namespace HaagerupIzumi.C8
namespace LatticeVOA

set_option profiler true
set_option profiler.threshold 50
set_option Elab.async false

'''
FOOTER = '\nend LatticeVOA\nend HaagerupIzumi.C8\n'


def main():
    cs = checks()
    if sys.argv[1] == 'probe':
        c = max(cs, key=cost)
        text = HEADER.format(title='Probe (scratch): the costliest PCT check', secs='?')
        (HERE / 'drafts' / 'PCTProbe.lean').write_text(text + theorem(c) + FOOTER)
        print(json.dumps({'probe': c[1], 'cost': cost(c), 'total': sum(map(cost, cs)),
                          'top': sorted(map(cost, cs))[-5:]}))
        return
    ms_per_unit = float(sys.argv[2])
    budget = float(sys.argv[3]) if len(sys.argv) > 3 else 2500.0
    files, cur, acc = [], [], 0.0
    for c in cs:
        t = cost(c) * ms_per_unit
        if cur and acc + t > budget:
            files.append((cur, acc))
            cur, acc = [], 0.0
        cur.append(c)
        acc += t
    files.append((cur, acc))
    for i, (group, acc) in enumerate(files):
        text = HEADER.format(title=f'PCT certificate, part {i}', secs=f'{acc / 1000:.1f}')
        text += '\n'.join(theorem(c) for c in group) + FOOTER
        (LEAN / f'PCTRel{i:02d}.lean').write_text(text)
    print(json.dumps({'files': len(files), 'checks': [len(g) for g, _ in files],
                      'est_s': [round(a / 1000, 2) for _, a in files]}))


if __name__ == '__main__':
    main()
