#!/usr/bin/env python3
"""Convert samples.json (made by export_samples.py) into Lean source for the W1 checks.

Pure string processing (json + fractions); it does not import the lattice engine.

    python3 lean/tools/lattice_export/gen_lean.py

writes (in lean/HaagerupIzumi/C8/Lattice/)
    Data.lean                      roots, currents, conformal vector (readable literals)
    CentralCharge.lean             omega_(3) omega = 4: one kernel check per term of omega
    SamplesA.lean ... SamplesF.lean, Samples.lean
                                   the 822 mode samples, one theorem per sample, split
                                   into files of at most ~2 s kernel time (memory)

Vectors are written sorted in the order of `LatticeVOA.stateCmp` (Python's `sorted` on
(momentum tuple, code tuple)), so that kernel checks are plain list equalities.  Sample data
use natural-number literals only (signed integers zigzag encoded, see `LatticeVOA.unzig`):
elaborating many `ℤ` literals in nested lists is far slower.
"""
import json
import textwrap
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[1] / 'HaagerupIzumi' / 'C8' / 'Lattice'
DATA = json.loads((HERE / 'samples.json').read_text())


def z(n):
    return f'({n})' if n < 0 else str(n)


def state(mom, osc):
    return 'S ' + ' '.join(z(c) for c in mom) + ' [' + ', '.join(str(k) for k in osc) + ']'


def mom(m):
    return '⟨' + ', '.join(str(c) for c in m) + '⟩'


def rat(c):
    c = Fraction(c)
    if c.denominator == 1:
        return str(c.numerator)
    return f'{c.numerator}/{c.denominator}'


def vec(terms):
    """terms: list of (mom, osc, Fraction)."""
    terms = sorted((tuple(m), tuple(o), Fraction(c)) for m, o, c in terms)
    keys = [(m, o) for m, o, _ in terms]
    assert len(set(keys)) == len(keys), 'duplicate state'
    assert all(c != 0 for _, _, c in terms)
    if not terms:
        return '[]'
    return '[' + ', '.join(f'({state(m, o)}, {rat(c)})' for m, o, c in terms) + ']'


def field_vec(v):
    """A vector over Q(s,t) whose s, t, st components vanish."""
    out = []
    for m, o, coeffs in v:
        cs = [Fraction(c) for c in coeffs]
        assert cs[1] == cs[2] == cs[3] == 0, 'irrational coefficient'
        out.append((m, o, cs[0]))
    return vec(out)


HEADER = 'module\n\n{imports}\n\n@[expose] public section\n'


def write_data():
    roots = DATA['roots']
    assert len(roots) == DATA['n_roots'] == 78
    hL, eL, fL = DATA['currents_left']
    hR, eR, fR = DATA['currents_right']
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.Fock')]
    lines.append('''/-!
# Data exported from the Python engine: roots, currents, conformal vector

Generated by `lean/tools/lattice_export/gen_lean.py` from `samples.json`
(`export_samples.py`, engine `hi_cft_20260923_c8_exact.py`).  Nothing here is assumed: the
roots are *proved* to be all norm-two vectors in `Lattice/Roots.lean`, and the currents
and `ω` are just the explicit vectors of `eq:leftcurrents`, `eq:rightcurrents` (lines
1910–1930 of `c8_expanded_20260929/haagerup_c8_expanded.tex`) and `ω = ½ ∑ G⁻¹ᵢⱼ hᵢ(-1)hⱼ(-1)𝟏`.

* `roots`: the 78 roots of `E₆ ⊕ A₂` in simple-root coordinates (sorted).
* `hL = α_L(-1)𝟏`, `eL = e^{α_L}`, `fL = -e^{-α_L}` with `α_L = (-1,-2,-3,-2,-1,-2,0,0)`.
* `hR = h_R(-1)𝟏`, `eR = ∑_{cᵢ≠0} e^{αᵢ}`, `fR = -∑ cᵢ e^{-αᵢ}`, `c = (5,8,9,8,5,0,2,2)`.
* `omega`: the conformal vector (Python `omega()`).
-/

namespace HaagerupIzumi.C8
namespace LatticeVOA
''')
    lines.append('/-- The 78 roots of `E₆ ⊕ A₂` (simple-root coordinates, sorted). -/')
    lines.append('def roots : List Mom :=')
    body = ',\n    '.join(mom(r) for r in sorted(map(tuple, roots)))
    lines.append(f'  [{body}]\n')
    for name, v, doc in (('hL', hL, '`H_L = α_L(-1)𝟏`'), ('eL', eL, '`E_L = e^{α_L}`'),
                         ('fL', fL, '`F_L = -e^{-α_L}`'), ('hR', hR, '`H_R = h_R(-1)𝟏`'),
                         ('eR', eR, '`E_R = ∑_{cᵢ ≠ 0} e^{αᵢ}`'),
                         ('fR', fR, '`F_R = -∑ cᵢ e^{-αᵢ}`'),
                         ('omega', DATA['omega'], 'The conformal vector `ω`')):
        lines.append(f'/-- {doc}. -/')
        lines.append(f'def {name} : Vec :=\n  {field_vec(v)}\n')
    lines.append('end LatticeVOA\nend HaagerupIzumi.C8\n')
    (LEAN / 'Data.lean').write_text('\n'.join(lines))


def zz(n):
    """Zigzag encoding (inverse of `LatticeVOA.unzig`)."""
    return 2 * n if n >= 0 else -2 * n - 1


def enc_state(m, o):
    return '[' + ', '.join([str(zz(c)) for c in m] + [str(k) for k in o]) + ']'


def enc_vec(terms):
    """Rows `[num, den, m0, …, m7, codes…]`, sorted like `vec`."""
    terms = sorted((tuple(m), tuple(o), Fraction(c)) for m, o, c in terms)
    assert len({(m, o) for m, o, _ in terms}) == len(terms)
    return [f'[{zz(c.numerator)}, {c.denominator}, ' + enc_state(m, o)[1:] for m, o, c in terms]


def state_str(st):
    return state(*st)


PARTS = {
    'SamplesA': ([0, 1, 2, 3], None),
    'SamplesB': ([4, 5], None),
    'SamplesC': ([6, 7, 8], None),
    'SamplesD': ([10, 11, 13], None),
    'SamplesE': ([12], (0, 30)),
    'SamplesF': ([12], (30, 60)),
    'Samples': ([9], None),
}


def groups_of_samples():
    groups = {}
    for idx, s in enumerate(DATA['samples']):
        key = (tuple(s['u'][0]), tuple(s['u'][1]))
        groups.setdefault(key, []).append(idx)
    return list(groups.items())


def write_samples(name, group_ids, window=None, title=None):
    samples = DATA['samples']
    groups = groups_of_samples()
    chosen = []
    for g in group_ids:
        idxs = groups[g][1]
        if window is not None:
            idxs = idxs[window[0]:window[1]]
        chosen.append((g, idxs))
    nsamp = sum(len(ix) for _, ix in chosen)
    nterms = sum(len(samples[i]['out']) for _, ix in chosen for i in ix)
    desc = ', '.join(f'group {g} (`u = {state_str(groups[g][0])}`, {len(ix)} samples)'
                     for g, ix in chosen)
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.Modes')]
    lines.append(f'''/-!
# {title or f"Cross-check of `basisMode` against the Python engine: {nsamp} samples"}

{textwrap.fill(f"Part of the W1 cross-check (`C8/ROADMAP.md`): {desc}; {nterms} output terms in total.", 95)}
Generated by `lean/tools/lattice_export/gen_lean.py` from `samples.json`
(`export_samples.py`: `basis_mode(u, n, v)` of `hi_cft_20260923_proof_general_modes_v2.py`
with `install(4)`, for all `u, v` in the export lists and all `n ∈ [-3, 4]` with output grade
`0 ≤ wt u + wt v - n - 1 ≤ 4`; the 822 samples are split over `SamplesA`–`SamplesF` and
`Samples` to bound the memory of one Lean process).

Each theorem `sample_i_ok` states that the Lean `basisMode u n v` equals the vector exported by
the Python engine for sample `i`, by kernel evaluation (`decide +kernel`); the data are
not hypotheses.  Encoding (natural-number literals only, to keep elaboration cheap; signed
integers are zigzag encoded, `unzig`): a sample is a list of rows `[[zz n], u, v, t₁, t₂, …]`,
a state row is `[zz m₀, …, zz m₇, codes…]` (`decState`) and an output term row is
`[zz num, den, zz m₀, …, zz m₇, codes…]` (`decTerm`, coefficient `num/den`).  Kernel times
are printed by `set_option profiler true` (sequential elaboration, so per declaration).
-/

namespace HaagerupIzumi.C8
namespace LatticeVOA

set_option profiler true
set_option profiler.threshold 20
set_option Elab.async false
''')
    for g, ix in chosen:
        for i in ix:
            sm = samples[i]
            u = state_str(sm['u'])
            v = state_str(sm['v'])
            parts = [f'[{zz(sm["n"])}]', enc_state(*sm['u']), enc_state(*sm['v'])]
            parts += enc_vec([(m, o, Fraction(c)) for m, o, c in sm['out']])
            lines.append(f'/-- Sample {i} (group {g}): `u = {u}`, `n = {sm["n"]}`, `v = {v}`, '
                         f'{len(sm["out"])} output terms. -/')
            lines.append(f'noncomputable def sample_{i} : List (List ℕ) :=\n  ['
                         + ',\n    '.join(parts) + ']\n')
            lines.append(f'theorem sample_{i}_ok :\n'
                         f'    basisMode (sampleU sample_{i}) (sampleN sample_{i}) (sampleV sample_{i}) =\n'
                         f'      sampleOut sample_{i} := by\n'
                         '  decide +kernel\n')
    allix = [i for _, ix in chosen for i in ix]
    heavy = max(allix, key=lambda i: len(samples[i]['out']))
    for i in sorted({allix[0], heavy, allix[-1]}):
        lines.append(f'#print axioms sample_{i}_ok')
    lines.append('\nend LatticeVOA\nend HaagerupIzumi.C8\n')
    (LEAN / f'{name}.lean').write_text('\n'.join(lines))
    print(name, 'samples', nsamp, 'terms', nterms)


def write_central_charge():
    """`ω_(3) ω = 4 𝟏` split into the 24 terms of `ω` (one kernel check per term)."""
    terms = sorted((tuple(m), tuple(o), Fraction(c[0])) for m, o, c in DATA['omega'])
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.Semantic\n'
                                   'public import HaagerupIzumi.C8.Lattice.Data')]
    lines.append('''/-!
# The central-charge identity `ω_(3) ω = 4 𝟏`

Work item W1, step 5 (`C8/ROADMAP.md`).  Generated by `lean/tools/lattice_export/gen_lean.py`.
For each of the 24 terms `hₐ(-1)h_b(-1)𝟏` of `ω = ½ ∑ G⁻¹ₐᵦ hₐ(-1)h_b(-1)𝟏`
(`Lattice/Data.lean`), `omega3_k` checks by kernel evaluation that
`(hₐ(-1)h_b(-1)𝟏)_(3) ω = (αₐ, α_b) 𝟏` (`omegaPair`); `omega_sum` checks
`∑ cₐᵦ (αₐ, α_b) = 4`, and `central_charge` combines them by linearity
(`Y_toFock_eq_of_terms`): `ω_(3) ω = 4 𝟏`, i.e. `(c/2) 𝟏` with `c = 8 = rank L` for the Virasoro
structure of `ω` (whose other relations, `L(0)` and `L(-1)`, are part of `FLMInput` in
`Lattice/VOA.lean`; `ω_(1) ω = 2ω`, `ω_(2) ω = 0` are not checked here).  Each check is a separate
declaration to keep the kernel memory of one declaration small.  No hypotheses.
-/

namespace HaagerupIzumi.C8
namespace LatticeVOA

set_option profiler true
set_option profiler.threshold 20
set_option Elab.async false

/-- `(αₐ, α_b)` for the monomial `hₐ(-1) h_b(-1)`; `0` for other code lists. -/
def omegaPair (s : State) : ℚ :=
  match s.2 with
  | [a, b] => (Mom.pairSimple a (Mom.simple b) : ℚ)
  | _ => 0

/-- Linearity in the first argument: if every term `(s, c)` of `v` satisfies
`(s)_(m) w = d(s) y`, then `(v)_(m) w = (∑ c d(s)) y`. -/
theorem Y_toFock_eq_of_terms (v w : Vec) (m : ℤ) (y : Vec) (d : State → ℚ)
    (h : ∀ p ∈ v, mode [(p.1, 1)] m w = smul (d p.1) y) :
    Y (toFock v) m (toFock w) = (v.map fun p => p.2 * d p.1).sum • toFock y := by
  induction v with
  | nil => simp [Y]
  | cons p v ih =>
    have hp := h p List.mem_cons_self
    have ih' := ih fun q hq => h q (List.mem_cons_of_mem _ hq)
    have h1 : Y (toFock [(p.1, 1)]) m (toFock w) = d p.1 • toFock y := by
      rw [← toFock_mode, hp, toFock_smul]
    have h2 : Y (Finsupp.single p.1 p.2) m (toFock w) =
        p.2 • Y (toFock [(p.1, 1)]) m (toFock w) := by
      simp only [Y, toFock_cons, toFock_nil, add_zero, Finsupp.linearCombination_single,
        LinearMap.smul_apply, one_smul]
    rw [toFock_cons, List.map_cons, List.sum_cons, add_smul, ← ih',
      show Y (Finsupp.single p.1 p.2 + toFock v) m =
        Y (Finsupp.single p.1 p.2) m + Y (toFock v) m from
          map_add (Finsupp.linearCombination ℚ fun u => modeOp u m) _ _,
      LinearMap.add_apply, h2, h1, smul_smul]

''')
    names = []
    for k, (m, o, c) in enumerate(terms):
        st = state(m, o)
        names.append((k, st))
        lines.append(f'theorem omega3_{k} :\n    mode [({st}, 1)] 3 omega = smul (omegaPair ({st})) vac := by\n'
                     '  decide +kernel\n')
    lines.append('''theorem omega3_terms : ∀ p ∈ omega, mode [(p.1, 1)] 3 omega = smul (omegaPair p.1) vac := by
  intro p hp
  simp only [omega, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with ''' + ' | '.join(['rfl'] * len(terms)) + '''
  exacts [''' + ', '.join(f'omega3_{k}' for k, _ in names) + ''']

theorem omega_sum : (omega.map fun p => p.2 * omegaPair p.1).sum = 4 := by
  decide +kernel

/-- **`ω_(3) ω = 4 𝟏`** (the central-charge term `c/2` of `L(2) ω`, with `c = 8`). -/
theorem central_charge : Y (toFock omega) 3 (toFock omega) = (4 : ℚ) • toFock vac := by
  rw [Y_toFock_eq_of_terms omega omega 3 vac omegaPair omega3_terms, omega_sum]

#print axioms central_charge

end LatticeVOA
end HaagerupIzumi.C8
''')
    (LEAN / 'CentralCharge.lean').write_text('\n'.join(lines))
    print('CentralCharge terms', len(terms))


if __name__ == '__main__':
    write_data()
    write_central_charge()
    for name, (gs, window) in PARTS.items():
        write_samples(name, gs, window)
