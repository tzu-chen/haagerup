#!/usr/bin/env python3
"""Convert s2.json (made by export_s2.py) into Lean source for the W2 minimal-generation replay.

Pure string processing (json + fractions); it does not import the lattice engine.

    python3 lean/tools/lattice_export/gen_s2.py

writes (in lean/HaagerupIzumi/C8/Lattice/)
    S2Data.lean          u, the 120 echelon basis vectors r_k, their pivots, `combo`, `s2op`
    S2Rel<NN>.lean       one kernel theorem per relation 'source = s r_new + sum c_i r_k_i'
                         (the relations that create a basis vector), a few per file
    S2Pivots.lean        the triangularity of the basis at its pivots (independence)
    S2MinGen.lean        membership of every r_k in the closure space (generated proofs)

Status (4 Oct 2026): everything is built in lean/HaagerupIzumi/C8/Lattice/.  The generated
S2Pivots.lean is NOT used: as one file it exhausted 4 GiB; it was replaced by hand-split files
(S2Coeff, S2PivotsA-F, S2Tri00-32, assembly S2Echelon; see Lattice/Benchmark.md section 5), and
S2MinGen.lean now imports S2Echelon and has a hand fix in s2u_rel_mem.  Do not re-run this
generator into the tree without porting that layout (it would overwrite S2MinGen.lean and write
the monolithic S2Pivots.lean again).

Vectors over Q(s, t) are written as four rational components (`Vec4`, `decVec4`), each a list
of term rows [zz num, den, zz m0, ..., zz m7, codes...] sorted like `LatticeVOA.stateCmp`;
coefficients as `decQA [zz a, a', zz b, b', zz c, c', zz d, d']`.
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[1] / 'HaagerupIzumi' / 'C8' / 'Lattice'
DATA = json.loads((HERE / 's2.json').read_text())
CURRENTS = ['hL', 'eL', 'fL', 'hR', 'eR', 'fR']
OPSIZE = [1, 1, 7, 7, 3]


def zz(n):
    return 2 * n if n >= 0 else -2 * n - 1


def enc_row(m, o, c):
    return '[' + ', '.join([str(zz(c.numerator)), str(c.denominator)] + [str(zz(x)) for x in m]
                           + [str(k) for k in o]) + ']'


def enc_state(m, o):
    return '[' + ', '.join([str(zz(x)) for x in m] + [str(k) for k in o]) + ']'


def components(v):
    comps = [[], [], [], []]
    for m, o, cs in v:
        for i in range(4):
            f = Fraction(cs[i])
            if f != 0:
                comps[i].append((tuple(m), tuple(o), f))
    return [sorted(c) for c in comps]


def vec4(v, indent='    '):
    comps = components(v)
    parts = []
    for c in comps:
        if not c:
            parts.append('[]')
        else:
            parts.append('[' + (',\n' + indent + ' ').join(enc_row(*t) for t in c) + ']')
    return 'decVec4\n' + indent + ('\n' + indent).join(parts)


def qa(cs):
    fs = [Fraction(x) for x in cs]
    return 'decQA [' + ', '.join(f'{zz(f.numerator)}, {f.denominator}' for f in fs) + ']'


def pivot(v):
    return min((tuple(m), tuple(o)) for m, o, cs in v)


HEADER = 'module\n\n{imports}\n\n@[expose] public section\n'
NS_OPEN = '\nnamespace HaagerupIzumi.C8\nnamespace LatticeVOA\n'
NS_CLOSE = '\nend LatticeVOA\nend HaagerupIzumi.C8\n'


def write_data():
    B = DATA['basis']
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.QA\n'
                                   'public import HaagerupIzumi.C8.Lattice.Data')]
    lines.append('''/-!
# Data of the minimal-generation record (`hi_cft_20260923_c8_minimal_generators.json`)

Generated by `lean/tools/lattice_export/gen_s2.py` from `s2.json` (`export_s2.py`, a replay of
`hi_cft_20260923_c8_minimal_generators.py` with an instrumented echelon span).  These are data,
not hypotheses; their properties are kernel-checked in `S2Rel*.lean` and `S2Pivots.lean`.

* `s2u`: the three-vertex weight-two field `u` (coefficients in `ℚ(√13, √-3)`).
* `s2r_k`, `k < 120`: the echelon basis of the weight-two space `S₂` in insertion order;
  `s2basis` lists them, `s2piv` lists their pivot states (the least state of each `r_k`).
* `s2op o`, `s2opIdx o`: the five operators `E_L(0), F_L(0), E_R(0), F_R(0), u(1)` of the record.
* `combo`: the vector `∑ cᵢ vᵢ` of a list of coefficients and vectors.
-/
''')
    lines.append(NS_OPEN)
    lines.append('''/-- `∑ cᵢ vᵢ`. -/
def combo : List (QA × Vec4) → Vec4
  | [] => Vec4.zero
  | p :: l => Vec4.add (Vec4.smulQA p.1 p.2) (combo l)
''')
    lines.append(f'/-- The field `u`. -/\nnoncomputable def s2u : Vec4 :=\n  {vec4(DATA["u"])}\n')
    lines.append('''/-- The operators of the record: `0 ↦ E_L`, `1 ↦ F_L`, `2 ↦ E_R`, `3 ↦ F_R` (zero modes),
`4 ↦ u` (mode `1`). -/
noncomputable def s2op : ℕ → Vec4
  | 0 => Vec4.ofVec eL
  | 1 => Vec4.ofVec fL
  | 2 => Vec4.ofVec eR
  | 3 => Vec4.ofVec fR
  | _ => s2u

/-- The mode index of the operators of the record. -/
def s2opIdx : ℕ → ℤ
  | 4 => 1
  | _ => 0
''')
    for k, v in enumerate(B):
        lines.append(f'/-- Basis vector `r_{k}` of `S₂`. -/\nnoncomputable def s2r_{k} : Vec4 :=\n  {vec4(v)}\n')
    lines.append('/-- The echelon basis of `S₂`. -/\nnoncomputable def s2basis : List Vec4 :=\n  ['
                 + ', '.join(f's2r_{k}' for k in range(len(B))) + ']\n')
    lines.append('/-- The pivot states. -/\nnoncomputable def s2piv : List State :=\n  ['
                 + ',\n    '.join(f'decState {enc_state(*pivot(v))}' for v in B) + ']\n')
    lines.append(NS_CLOSE)
    (LEAN / 'S2Data.lean').write_text('\n'.join(lines))


def source_term(src):
    if src[0] == 'initial':
        i = src[1]
        if i < 6:
            return f'Vec4.mode (Vec4.ofVec {CURRENTS[i]}) (-2) (Vec4.ofVec vac)'
        if i < 42:
            c, d = divmod(i - 6, 6)
            return f'Vec4.mode (Vec4.ofVec {CURRENTS[c]}) (-1) (Vec4.ofVec {CURRENTS[d]})'
        if i == 42:
            return 'Vec4.ofVec omega'
        return 's2u'
    o, k = src[1], src[2]
    return f'Vec4.mode (s2op {o}) (s2opIdx {o}) s2r_{k}'


def combo_term(coeffs):
    if not coeffs:
        return 'combo []'
    return 'combo [' + ', '.join(f'({qa(c)}, s2r_{k})' for k, c in coeffs) + ']'


def rel_theorem(idx, r):
    src = source_term(r['source'])
    rhs = combo_term(r['coeffs'])
    if r['new'] is not None:
        rhs = f'Vec4.add (Vec4.smulQA ({qa(r["scale"])}) s2r_{r["new"]})\n      ({rhs})'
        inv = (f'\n\ntheorem s2scale_{idx} :\n    QA.mul ({qa(r["scale"])}) (QA.inv ({qa(r["scale"])})) = QA.one := by\n'
               '  decide +kernel')
    else:
        inv = ''
    return (f'/-- Relation {idx}: source `{r["source"]}`, new basis vector `{r["new"]}`. -/\n'
            f'theorem s2rel_{idx} :\n    {src} =\n      {rhs} := by\n  decide +kernel{inv}\n')


def rel_cost(r):
    B = DATA['basis']
    if r['source'][0] == 'op':
        return OPSIZE[r['source'][1]] * len(B[r['source'][2]]) + 20
    i = r['source'][1]
    return 49 if 6 <= i < 42 else 10


def write_rel_files(budget=900, only_new=True, prefix='S2Rel'):
    R = DATA['relations']
    items = [(idx, r) for idx, r in enumerate(R) if (r['new'] is not None) or not only_new]
    files = []
    cur, c = [], 0
    for idx, r in items:
        cost = rel_cost(r)
        if cur and c + cost > budget:
            files.append(cur)
            cur, c = [], 0
        cur.append((idx, r))
        c += cost
    if cur:
        files.append(cur)
    for n, group in enumerate(files):
        name = f'{prefix}{n:02d}'
        lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.S2Data')]
        lines.append(f'''/-!
# Minimal-generation relations, part {n}

Generated by `lean/tools/lattice_export/gen_s2.py`.  Each `s2rel_i` is relation `i` of the
minimal-generator record: the source vector (an initial vector `c_(-2)𝟏`, `c_(-1)d`, `ω`, `u`,
or an operator applied to an earlier basis vector, *computed* here by the lattice modes) equals
`s r_new + ∑ cᵢ r_kᵢ`, checked by kernel evaluation; `s2scale_i` checks the inverse of `s`.
-/
''')
        lines.append(NS_OPEN)
        lines.append('set_option profiler true\nset_option profiler.threshold 50\n'
                     'set_option Elab.async false\n')
        for idx, r in group:
            lines.append(rel_theorem(idx, r))
        lines.append(NS_CLOSE)
        (LEAN / f'{name}.lean').write_text('\n'.join(lines))
    return files


def rel_cost_ms(r):
    B = DATA['basis']
    rhs = sum(len(B[k]) for k, _ in r['coeffs']) + (len(B[r['new']]) if r['new'] is not None else 0)
    if r['source'][0] == 'op':
        calls = OPSIZE[r['source'][1]] * len(B[r['source'][2]])
    else:
        i = r['source'][1]
        calls = 49 if 6 <= i < 42 else 2
    return 8.5 * calls + rhs + 20


def partition(items, budget):
    files, cur, c = [], [], 0
    for idx, r in items:
        cost = rel_cost_ms(r)
        if cur and c + cost > budget:
            files.append(cur)
            cur, c = [], 0
        cur.append((idx, r))
        c += cost
    if cur:
        files.append(cur)
    return files


def write_rels(budget=6000):
    R = DATA['relations']
    items = [(idx, r) for idx, r in enumerate(R) if r['new'] is not None]
    files = partition(items, budget)
    for n, group in enumerate(files):
        name = f'S2Rel{n:02d}'
        lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.S2Data')]
        lines.append(f'''/-!
# Minimal-generation relations, part {n}

Generated by `lean/tools/lattice_export/gen_s2.py`.  Each `s2rel_i` is relation `i` of the
minimal-generator record that creates a basis vector: the source vector (an initial vector
`c_(-2)𝟏`, `c_(-1)d`, `ω`, `u`, or an operator applied to an earlier basis vector, *computed*
here with the lattice modes) equals `s r_new + ∑ cᵢ r_kᵢ`, checked by kernel evaluation;
`s2scale_i` checks the inverse of `s`.  Estimated kernel time of this file: about
{sum(rel_cost_ms(r) for _, r in group) / 1000:.1f} s.
-/
''')
        lines.append(NS_OPEN)
        lines.append('set_option profiler true\nset_option profiler.threshold 100\n'
                     'set_option Elab.async false\n')
        for idx, r in group:
            lines.append(rel_theorem(idx, r))
        lines.append(NS_CLOSE)
        (LEAN / f'{name}.lean').write_text('\n'.join(lines))
    return files


def write_pivots(chunk=20):
    B = DATA['basis']
    n = len(B)
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.S2Data')]
    lines.append('''/-!
# The echelon basis of `S₂`: canonical states, grades and triangularity at the pivots

Generated by `lean/tools/lattice_export/gen_s2.py`.  Kernel-checked facts about the data of
`S2Data.lean`: all states of `u` and of the `r_k` are canonical (sorted code lists) and the `r_k`
have grade two; `r_k` has coefficient `1` at its pivot and `0` at the pivots of all earlier
`r_j` (`j < k`), which makes the `r_k` linearly independent (`S2Link.lean`).
-/
''')
    lines.append(NS_OPEN)
    lines.append('set_option profiler true\nset_option profiler.threshold 100\n'
                 'set_option Elab.async false\n')
    lines.append('theorem s2u_valid : s2u.AllStates Valid := by\n  decide +kernel\n')
    for k in range(n):
        lines.append(f'theorem s2r_{k}_states : s2r_{k}.AllStates fun s => Valid s ∧ grade s = 2 := by\n'
                     '  decide +kernel\n')
    pats = ' | '.join(['rfl'] * n)
    ex = ', '.join(f's2r_{k}_states' for k in range(n))
    lines.append('theorem s2basis_states : ∀ x ∈ s2basis, x.AllStates fun s => Valid s ∧ grade s = 2 := by\n'
                 '  intro x hx\n  simp only [s2basis, List.mem_cons, List.not_mem_nil, or_false] at hx\n'
                 f'  rcases hx with {pats}\n  exacts [{ex}]\n')
    lines.append(f'theorem s2basis_length : s2basis.length = {n} := by\n  decide +kernel\n')
    lines.append(f'theorem s2piv_valid : ∀ j < {n}, Valid (s2piv.getD j vacState) := by\n  decide +kernel\n')
    lines.append(f'theorem s2piv_diag : ∀ k < {n}, Vec4.coeff (s2basis.getD k Vec4.zero) (s2piv.getD k vacState) =\n'
                 '    QA.one := by\n  decide +kernel\n')
    for a in range(0, n, chunk):
        b = min(n, a + chunk)
        lines.append(f'theorem s2piv_low_{a} : ∀ k < {n}, {a} ≤ k → k < {b} → ∀ j < k,\n'
                     '    Vec4.coeff (s2basis.getD k Vec4.zero) (s2piv.getD j vacState) = QA.zero := by\n'
                     '  decide +kernel\n')
    lines.append(f'theorem s2piv_low : ∀ k < {n}, ∀ j < k,\n'
                 '    Vec4.coeff (s2basis.getD k Vec4.zero) (s2piv.getD j vacState) = QA.zero := by\n'
                 '  intro k hk\n'
                 + ''.join(f'  by_cases h{a} : k < {min(n, a + chunk)}\n'
                           f'  · exact s2piv_low_{a} k hk (by omega) h{a}\n'
                           for a in range(0, n, chunk)) + '  omega\n')
    lines.append(NS_CLOSE)
    (LEAN / 'S2Pivots.lean').write_text('\n'.join(lines))


def current_or(name):
    i = CURRENTS.index(name)
    t = 'rfl' if i == 5 else 'Or.inl rfl'
    for _ in range(i):
        t = f'Or.inr ({t})'
    return f'({t})'


def source_proof(src):
    if src[0] == 'initial':
        i = src[1]
        if i < 6:
            return f'src_T hW {current_or(CURRENTS[i])}'
        if i < 42:
            c, d = divmod(i - 6, 6)
            return f'src_mm hW {current_or(CURRENTS[c])} {current_or(CURRENTS[d])}'
        if i == 42:
            return 'src_omega hW'
        return 'src_u hW'
    o, k = src[1], src[2]
    return (f'src_op hW s2u_valid {o} (by norm_num) (s2r_{k}_states.mono fun _ h => h.1) '
            f'(s2mem_{k} hW)')


def members_proof(coeffs, memname, arg):
    if not coeffs:
        return '(fun _ hp => absurd hp List.not_mem_nil)'
    pats = ' | '.join(['rfl'] * len(coeffs))
    ex = ', '.join(f'{memname}_{k} {arg}'.strip() for k, _ in coeffs)
    return ('(by\n      intro p hp\n      simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n'
            f'      rcases hp with {pats}\n      exacts [{ex}])')


def write_mingen(rel_files):
    R = DATA['relations']
    B = DATA['basis']
    n = len(B)
    imports = ['public import HaagerupIzumi.C8.Lattice.S2Core',
               'public import HaagerupIzumi.C8.Lattice.S2Pivots']
    imports += [f'public import HaagerupIzumi.C8.Lattice.S2Rel{i:02d}' for i in range(len(rel_files))]
    lines = [HEADER.format(imports='\n'.join(imports))]
    lines.append('''/-!
# Every basis vector of `S₂` lies in the closure of the generators (generated proofs)

Generated by `lean/tools/lattice_export/gen_s2.py`.  `s2mem_k hW`: for every subspace `W`
satisfying the closure conditions `S2Closed W` (it contains `ω`, `u`, `T x` and `x_(-1) y` for
currents `x, y`, and is stable under the current zero modes and `u_(1)`), the basis vector `r_k`
lies in `W`, by `mem_of_new` along the relations of the record in insertion order.
`s2basis_mem` collects them; `s2omega_rel_mem`, `s2u_rel_mem` express `ω` and `u` through the
basis (relations 42 and 43).
-/
''')
    lines.append(NS_OPEN)
    for idx, r in enumerate(R):
        if r['new'] is None:
            continue
        k = r['new']
        lines.append(f'theorem s2mem_{k} {{W : Submodule ℂ V}} (hW : S2Closed W) : toV4 s2r_{k} ∈ W :=\n'
                     f'  mem_of_new s2rel_{idx} s2scale_{idx}\n    ({source_proof(r["source"])})\n'
                     f'    {members_proof(r["coeffs"], "s2mem", "hW")}\n')
    pats = ' | '.join(['rfl'] * n)
    ex = ', '.join(f's2mem_{k} hW' for k in range(n))
    lines.append('theorem s2basis_mem {W : Submodule ℂ V} (hW : S2Closed W) : ∀ x ∈ s2basis, toV4 x ∈ W := by\n'
                 '  intro x hx\n  simp only [s2basis, List.mem_cons, List.not_mem_nil, or_false] at hx\n'
                 f'  rcases hx with {pats}\n  exacts [{ex}]\n')
    # omega and u through the basis, in any W containing the r_k
    for idx, name, lhs in ((42, 'omega', 'toV4 (Vec4.ofVec omega)'), (43, 'u', 'toV4 s2u')):
        r = R[idx]
        assert r['new'] is not None
        lines.append(f'theorem s2{name}_rel_mem {{W : Submodule ℂ V}} (hr : ∀ x ∈ s2basis, toV4 x ∈ W) :\n'
                     f'    {lhs} ∈ W :=\n'
                     f'  src_mem_of_rel s2rel_{idx} (hr _ (by simp [s2basis]))\n'
                     f'    (fun p hp => by\n'
                     f'      simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n'
                     + (f'      rcases hp with {" | ".join(["rfl"] * len(r["coeffs"]))}\n'
                        f'      all_goals exact hr _ (by simp [s2basis]))\n' if r['coeffs'] else
                        '      exact hp.elim)\n'))
    lines.append(NS_CLOSE)
    (LEAN / 'S2MinGen.lean').write_text('\n'.join(lines))


def write_pilot(idxs):
    R = DATA['relations']
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.S2Data')]
    lines.append('/-! # Pilot: kernel cost of a few minimal-generation relations (scratch) -/\n')
    lines.append(NS_OPEN)
    lines.append('set_option profiler true\nset_option profiler.threshold 10\n'
                 'set_option Elab.async false\n')
    for idx in idxs:
        lines.append(rel_theorem(idx, R[idx]))
    lines.append(NS_CLOSE)
    (LEAN / 'S2Pilot.lean').write_text('\n'.join(lines))


if __name__ == '__main__':
    write_data()
    if len(sys.argv) > 1 and sys.argv[1] == 'pilot':
        write_pilot([int(a) for a in sys.argv[2:]])
    else:
        files = write_rels()
        print(len(files), 'relation files', [len(f) for f in files],
              [round(sum(rel_cost_ms(r) for _, r in f) / 1000, 1) for f in files])
        write_pivots()
        write_mingen(files)
