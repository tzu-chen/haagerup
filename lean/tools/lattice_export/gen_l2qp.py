#!/usr/bin/env python3
"""Lean replay of the Virasoro control L(2) q+ = c r2_000017 (omega_(3), modeQRF).

Written 4 October 2026 (16:45).  Pure text processing of p4.json, p4_controls/L2_qp.jsonl
(export_p4_controls.py, 90 states per sub-chunk) and the saved S2 rows (S2Saved.lean).

    python3 lean/tools/lattice_export/gen_l2qp.py [<out dir>]

Writes (namespace HaagerupIzumi.C8.LatticeVOA)
    P4SubL<k>.lean        sub-chunk inputs `p4sL_<c>_<j> : QVec` of q+ (90-state sub-chunks)
    P4SubLkL<c><x>.lean   component links, P4SubLkL<c>.lean `p4sL_<c>_link`
    P4ImgL2.lean          the exported images `p4i_L2_qp_<i>`
    P4ChkL2<ii>.lean      `p4c_L2_qp_<i>`: `nz4 (sort4 (toVec4Q (modeQRF omega 3 sub))) = image`
    P4MgL2.lean           `p4mg_L2_qp : sum4 images = combo [(c, s2sv_17)]`
    P4RL2.lean            `L2_qpV`, `L2_qp_mem`, `L2_P4_latticeDP`
"""
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402
import gen_p4ctl as gc  # noqa: E402
import p4_chunks  # noqa: E402

PROF = 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_l2qp.py`.  {body}\n-/\n' + g.NS_OPEN)


def mul(x, y):
    a, b, c, d = x
    e, f, gg, h = y
    return (a * e + 13 * b * f - 3 * c * gg - 39 * d * h, a * f + b * e - 3 * (c * h + d * gg),
            a * gg + c * e + 13 * (b * h + d * f), a * h + d * e + b * gg + c * f)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else g.LEAN
    lines = (HERE / 'p4_controls' / 'L2_qp.jsonl').read_text().splitlines()
    meta = json.loads(lines[0])
    recs = [json.loads(x) for x in lines[1:-1]]
    tail = json.loads(lines[-1])
    assert tail['matches_expected'] and meta['chunks'] == len(recs) and meta['mode'] == 3
    P4 = json.loads((HERE / 'p4.json').read_text())
    fields = {f['id']: f['vector'] for f in P4['fields']}
    subs = p4_chunks.control_subchunks(fields['P4_plus'], 'L2_qp', meta['states_per_chunk'])
    for (c, j, t), r in zip(subs, recs):
        assert (r['data_chunk'], r['sub'], r['n_states']) == (c, j, len(t))
    vc = [v for v in P4['virasoro_controls'] if v['L_mode'] == 2 and v['field'] == 'P4_plus'][0]
    assert vc['exact_residual_zero'] and len(vc['relation']) == 1 and vc['relation'][0][0] == 'r2_000017'
    coef = tuple(F(x) for x in vc['relation'][0][1])
    # the exported total equals coef * r2_000017 (saved row 17)
    import gen_s2saved
    R = gen_s2saved.load_rows2()
    import ast
    row = R['rows2'][17]['vector']
    row = ast.literal_eval(row) if isinstance(row, str) else row
    assert R['rows2'][17]['id'] == 'r2_000017'
    total = {(tuple(m), tuple(o)): tuple(F(x) for x in cs) for m, o, cs in tail['total']}
    prod = {(tuple(m), tuple(o)): mul(coef, tuple(F(x) for x in cs)) for m, o, cs in row}
    assert total == prod, 'export total != c * r2_000017'
    N = len(recs)
    sname = lambda c, j: f'p4sL_{c}_{j}'  # noqa: E731
    order = []

    subfile = {}
    for k, group in enumerate(gc.pack(subs, lambda t: 20 * len(t[2]))):
        text = header(['ModeQ'], f'Triplet `P4_plus`: 90-state sub-chunk inputs for `L(2)`, part {k}',
                      'Data (one `ℚ(√13, √-3)` coefficient per state).')
        for c, j, t in group:
            subfile[(c, j)] = f'P4SubL{k}'
            text += f'\nnoncomputable def {sname(c, j)} : QVec :=\n  {gc.qvec(t)}\n'
        text += g.NS_CLOSE
        (out / f'P4SubL{k}.lean').write_text(text)
        order.append(f'P4SubL{k}')
    text = header(['QA'], 'Control `L2_qp`: exported partial images',
                  'Data: `ω_(3)` of each sub-chunk, from `p4_controls/L2_qp.jsonl`, checked in `P4ChkL2*`.')
    for i, r in enumerate(recs):
        text += f'\nnoncomputable def p4i_L2_qp_{i} : Vec4 :=\n  {g.vec4(r["image"])}\n'
    text += g.NS_CLOSE
    (out / 'P4ImgL2.lean').write_text(text)
    order.append('P4ImgL2')
    nchunks = 1 + max(c for c, _, _ in subs)
    links = []
    for c in range(nchunks):
        js = [j for cc, j, _ in subs if cc == c]
        lst = ', '.join(sname(c, j) for j in js)
        imps = ['P4Ctl', f'P4DataP{c}'] + sorted({subfile[(c, j)] for j in js})
        for x in range(4):
            text = header(imps, f'`P4_plus`, chunk {c}, component c{x}: the 90-state sub-chunks add up to the data',
                          'Kernel check.')
            text += PROF
            text += (f'\ntheorem p4sL_{c}_link_c{x} :\n    (nz4 (sort4 (toVec4Q [{lst}].flatten))).c{x} =\n'
                     f'      p4P_{c}.c{x} := by\n  decide +kernel\n')
            text += g.NS_CLOSE
            (out / f'P4SubLkL{c}{x}.lean').write_text(text)
            links.append(f'P4SubLkL{c}{x}')
    alinks = []
    for c in range(nchunks):
        js = [j for cc, j, _ in subs if cc == c]
        lst = ', '.join(sname(c, j) for j in js)
        text = header(['P4Ctl2'] + [f'P4SubLkL{c}{x}' for x in range(4)],
                      f'`P4_plus`, chunk {c}: the 90-state sub-chunks add up to the data', 'Assembled by `vec4_ext`.')
        text += (f'\ntheorem p4sL_{c}_link :\n    nz4 (sort4 (toVec4Q [{lst}].flatten)) = p4P_{c} :=\n'
                 f'  vec4_ext p4sL_{c}_link_c0 p4sL_{c}_link_c1 p4sL_{c}_link_c2 p4sL_{c}_link_c3\n')
        text += g.NS_CLOSE
        (out / f'P4SubLkL{c}.lean').write_text(text)
        alinks.append(f'P4SubLkL{c}')
    checks = []
    for i, ((c, j, t), r) in enumerate(zip(subs, recs)):
        text = header(['P4Ctl', 'Data', subfile[(c, j)], 'P4ImgL2'], f'Control `L2_qp`, sub-chunk {i} (chunk {c}, part {j})',
                      'Kernel check of `ω_(3)` on the sub-chunk with `modeQRF` (`ModeHH.lean`).')
        text += PROF
        text += (f'\ntheorem p4c_L2_qp_{i} : (∀ q ∈ {sname(c, j)}, Valid q.1) ∧\n'
                 f'    nz4 (sort4 (toVec4Q (modeQRF omega 3 {sname(c, j)}))) = p4i_L2_qp_{i} := by\n'
                 '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4ChkL2{i:02d}.lean').write_text(text)
        checks.append(f'P4ChkL2{i:02d}')
    cterm = f'combo [({g.qa([str(x) for x in coef])}, s2sv_17)]'
    imgs = ', '.join(f'p4i_L2_qp_{i}' for i in range(N))
    text = header(['P4Ctl', 'P4ImgL2', 'S2Saved'], 'Control `L2_qp`: the partial images add up to `c · r2_000017`',
                  'Kernel check (`sum4`); `c` is the coefficient of the record (`p4.json`, `virasoro_controls`).')
    text += PROF
    text += f'\ntheorem p4mg_L2_qp :\n    sum4 [{imgs}] =\n      {cterm} := by\n  decide +kernel\n'
    text += g.NS_CLOSE
    (out / 'P4MgL2.lean').write_text(text)
    pairs = ', '.join(f'({sname(c, j)}, p4i_L2_qp_{i})' for i, (c, j, _) in enumerate(subs))
    alt = ' | '.join(['rfl'] * N)
    lk = ', '.join(f'toV4_eq_of_link p4sL_{c}_link' for c in range(nchunks))
    text = header(['P4L2Red', 'P4MgL2'] + alinks + checks,
                  'Control `L2_P₄` for the actual triplet',
                  '`ω_(3) q₊ = c · r2_000017` (per-sub-chunk checks `P4ChkL2*` with `modeQRF`, links `P4SubLkL*`, '
                  'merge `P4MgL2`), hence `ω_(3) q₊ ∈ S2span` by `S2savedSpan_eq`, and the `LowerCertificate` field '
                  '`L2_P₄` for `latticeDP` by `L2_P4_latticeDP_of_qp` (`P4L2Red.lean`).')
    text += f'''
noncomputable def p4pairs_L2_qp : List (QVec × Vec4) :=
  [{pairs}]

theorem p4pairs_L2_qp_ok : ∀ p ∈ p4pairs_L2_qp,
    (∀ q ∈ p.1, Valid q.1) ∧ nz4 (sort4 (toVec4Q (modeQRF omega 3 p.1))) = p.2 := by
  intro p hp
  simp only [p4pairs_L2_qp, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with {alt}
  exacts [{", ".join(f"p4c_L2_qp_{i}" for i in range(N))}]

set_option maxHeartbeats 1000000 in
/-- **`L(2) q₊ = c · r2_000017`** in `V`. -/
theorem L2_qpV : modeC 3 omegaV qpV = toV4 ({cterm}) := by
  have h := ctl_pairs omega (fun p hp => (omega_states p hp).1) 3 p4pairs_L2_qp p4pairs_L2_qp_ok
  have hin : qpV = (p4pairs_L2_qp.map fun p => toVQ p.1).sum := by
    simp only [qpV, p4P, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    rw [{lk}]
    simp only [p4pairs_L2_qp, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    abel
  have hout : (p4pairs_L2_qp.map fun p => toV4 p.2).sum = toV4 ({cterm}) := by
    rw [show (p4pairs_L2_qp.map fun p => toV4 p.2) = [{imgs}].map toV4 from rfl,
      ← toV4_sum4, p4mg_L2_qp]
  rw [omegaV, hin, h, hout]

/-- `L(2) q₊ ∈ S₂`. -/
theorem L2_qp_mem : modeC 3 omegaV qpV ∈ S2span := by
  rw [L2_qpV]
  exact toV4_combo_saved_mem _
    (List.forall_mem_cons.2 ⟨s2sv_mem_17, fun _ h => absurd h List.not_mem_nil⟩)

/-- **Control `L2_P₄`** of `LowerCertificate` for the actual triplet. -/
theorem L2_P4_latticeDP (hF : FLMInput) (S₃ : Submodule ℂ V) (hS₃ : S₃ ≤ gradeC 3) :
    ∀ q ∈ (latticeDP hF S₃ hS₃).triplet,
      (latticeVOA hF).mode 3 (latticeVOA hF).ω q ∈ (latticeDP hF S₃ hS₃).S₂ :=
  L2_P4_latticeDP_of_qp hF S₃ hS₃ L2_qp_mem

#print axioms L2_P4_latticeDP
'''
    text += g.NS_CLOSE
    (out / 'P4RL2.lean').write_text(text)
    print(json.dumps({'data': order, 'links': links, 'alinks': alinks, 'checks': len(checks)}))


if __name__ == '__main__':
    main()
