#!/usr/bin/env python3
"""Lean data and state checks for the exact 956-dimensional weight-three space S3 (s3.json).

Written 4 October 2026; NOT run (it writes about 700 Lean files; run it only in a session that
will also build them).  Pure text processing (json + fractions); no modes.

    python3 lean/tools/lattice_export/gen_s3.py [--budget-literals 27000] [--rows-per-check 400]
                                                [--out lean/HaagerupIzumi/C8/Lattice]

Input: s3.json (export_s3.py; 956 rows of the checkpoint
hi_cft_20260923_next_grade4_checkpoint/checkpoint_000024 in basis order 'order3', 220,376 terms,
766,312 nonzero rational components, 8,646,319 literals).

Output (all in --out, namespace HaagerupIzumi.C8.LatticeVOA):
    S3Data<NNN>.lean   consecutive rows of order3, `s3r_<k> : Vec4` (k = position in order3),
                       packed to about --budget-literals literals per file (one row per file if it
                       is larger).  Measured for the same encoding (P4Data*, S3Probe): 27,000
                       literals elaborate in about 8.5 s at 0.77 GiB (olean about 1 MB), so about
                       320 files, about 45 min of queue time.  Imports QA only.
    S3St<NNN>.lean     per data file: `s3r_<k>_states : s3r_<k>.AllStates fun s =>
                       Valid s ∧ grade s = 3` by `decide +kernel`, grouped so that each file checks
                       at most --rows-per-check rational component rows (measured for the same
                       predicate without eigenvalues: about 1.5-3 ms per row, 0.2 GiB per kernel
                       second; 400 rows is about 1 s, below 1 GiB).  About 2,000 files at 400 rows;
                       raise --rows-per-check to 1,200 (about 3 s, 1.1 GiB) for about 650 files.
    S3Basis.lean       imports all S3Data files; `s3basis : List Vec4` (956 entries),
                       `s3piv : List State` (the pivot of each row: its least state, coefficient 1
                       in the checkpoint), `s3weight : List (ℤ × ℤ)` (the Cartan weight block);
                       the input for the triangularity checks (as S2Tri*: each row vanishes at the
                       pivots of the earlier rows of its weight block; blocks have at most 58 rows)
                       and for `S3span := span (toV4 <$> s3basis)`, `finrank S3span = 956`.
    S3States.lean      imports all S3St files; `s3basis_states : ∀ x ∈ s3basis, x.AllStates
                       fun s => Valid s ∧ grade s = 3` (by `rcases` over the 956 rows, as
                       S2Echelon.s2basis_states), hence `S3span ≤ gradeC 3`.
Not generated here (next steps, same patterns as S2): S3Tri* (triangularity, with the
state-comparison check of S2Coeff), the 956 recipes (`rows3[k].recipe`, `.elimination`,
`.scale`: S3 ≤ U and S3 = N3 + (S2)_0 S2) and the inputs of s3.json ('inputs': fields.json.gz).
"""
import argparse
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402  (encoding helpers; loads s2.json, harmless)


def literals(v):
    return sum(10 + len(o) for m, o, cs in v for x in cs if Fraction(x) != 0)


def comp_rows(v):
    return sum(1 for m, o, cs in v for x in cs if Fraction(x) != 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--budget-literals', type=int, default=27000)
    ap.add_argument('--rows-per-check', type=int, default=400)
    ap.add_argument('--out', default=str(g.LEAN))
    args = ap.parse_args()
    out = Path(args.out)
    S3 = json.loads((HERE / 's3.json').read_text())
    rows = S3['rows3']
    assert [r['id'] for r in rows] == S3['order3'] and len(rows) == 956

    # data files
    files, cur, acc = [], [], 0
    for k, r in enumerate(rows):
        n = literals(r['vector'])
        if cur and acc + n > args.budget_literals:
            files.append(cur)
            cur, acc = [], 0
        cur.append(k)
        acc += n
    files.append(cur)
    for i, ks in enumerate(files):
        text = g.HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.QA')
        text += f'''/-!
# Data of `S₃`, part {i}: rows {ks[0]}–{ks[-1]} of `order3`

Generated by `lean/tools/lattice_export/gen_s3.py` from `s3.json` (`export_s3.py`, checkpoint
`{S3['checkpoint']}`).  Data, not hypotheses.
-/
'''
        text += g.NS_OPEN
        for k in ks:
            r = rows[k]
            text += (f'\n/-- `{r["id"]}`, weight `{r["weight"]}`. -/\n'
                     f'noncomputable def s3r_{k} : Vec4 :=\n  {g.vec4(r["vector"])}\n')
        text += g.NS_CLOSE
        (out / f'S3Data{i:03d}.lean').write_text(text)

    # state checks
    checks, cur, acc = [], [], 0
    for i, ks in enumerate(files):
        for k in ks:
            n = comp_rows(rows[k]['vector'])
            if cur and acc + n > args.rows_per_check:
                checks.append(cur)
                cur, acc = [], 0
            cur.append((i, k))
            acc += n
    checks.append(cur)
    for j, group in enumerate(checks):
        imports = sorted({i for i, _ in group})
        text = g.HEADER.format(imports='\n'.join(
            f'public import HaagerupIzumi.C8.Lattice.S3Data{i:03d}' for i in imports))
        text += f'''/-!
# States of `S₃`, check {j}: rows {group[0][1]}–{group[-1][1]}

Generated by `gen_s3.py`.  Every state of these rows is canonical of grade three (kernel).
-/
'''
        text += g.NS_OPEN
        text += 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'
        for _, k in group:
            text += (f'\ntheorem s3r_{k}_states : s3r_{k}.AllStates fun s => Valid s ∧ grade s = 3 := by\n'
                     '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'S3St{j:04d}.lean').write_text(text)

    # basis list, pivots, weights
    imports = '\n'.join(f'public import HaagerupIzumi.C8.Lattice.S3Data{i:03d}'
                        for i in range(len(files)))
    text = g.HEADER.format(imports=imports)
    text += '''/-!
# The echelon basis of `S₃` (956 rows of the checkpoint, in basis order)

Generated by `gen_s3.py`.  `s3basis`, the pivots `s3piv` (least state of each row, coefficient 1)
and the Cartan weight blocks `s3weight`.
-/
'''
    text += g.NS_OPEN
    text += ('\nnoncomputable def s3basis : List Vec4 :=\n  ['
             + ', '.join(f's3r_{k}' for k in range(len(rows))) + ']\n')
    text += ('\ndef s3piv : List State :=\n  ['
             + ',\n    '.join(f'decState {g.enc_state(*r["pivot"])}' for r in rows) + ']\n')
    text += ('\ndef s3weight : List (ℤ × ℤ) :=\n  ['
             + ', '.join(f'({r["weight"][0]}, {r["weight"][1]})' for r in rows) + ']\n')
    text += g.NS_CLOSE
    (out / 'S3Basis.lean').write_text(text)

    imports = '\n'.join(['public import HaagerupIzumi.C8.Lattice.S3Basis'] +
                        [f'public import HaagerupIzumi.C8.Lattice.S3St{j:04d}' for j in range(len(checks))])
    text = g.HEADER.format(imports=imports)
    text += '''/-!
# All states of `S₃` are canonical of grade three

Generated by `gen_s3.py`, from the checks `S3St*.lean`.
-/
'''
    text += g.NS_OPEN
    text += ('\ntheorem s3basis_states : ∀ x ∈ s3basis, x.AllStates fun s => Valid s ∧ grade s = 3 := by\n'
             '  intro x hx\n  simp only [s3basis, List.mem_cons, List.not_mem_nil, or_false] at hx\n'
             '  rcases hx with ' + ' | '.join(['rfl'] * len(rows)) + '\n'
             '  exacts [' + ', '.join(f's3r_{k}_states' for k in range(len(rows))) + ']\n')
    text += g.NS_CLOSE
    (out / 'S3States.lean').write_text(text)
    print(json.dumps({'data_files': len(files), 'check_files': len(checks),
                      'literals': sum(literals(r['vector']) for r in rows),
                      'component_rows': sum(comp_rows(r['vector']) for r in rows)}))


if __name__ == '__main__':
    main()
