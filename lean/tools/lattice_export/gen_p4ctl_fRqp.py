#!/usr/bin/env python3
"""Redesigned Lean replay of the control fR_qp (F_R(0) q+ = q0): merge by output-state ranges.

Pure text processing (json + fractions: splitting exported vectors into pieces by state ranges,
no arithmetic on coefficients).  Complements gen_p4ctl.py (whose sub-chunk inputs P4SubP*,
images P4ImgFRP*, checks P4ChkFRP* are used unchanged) after the single merge check P4SumFRP
exhausted 4 GiB (job 150440-032c13).

    python3 lean/tools/lattice_export/gen_p4ctl_fRqp.py [<pieces>]

writes in lean/HaagerupIzumi/C8/Lattice/:
    P4SubLkP<c><x>.lean, c = 1..3, x = 0..3   sub-chunk links split by component
    P4SubLkP<c>.lean                          assembled links (vec4_ext)
    P4IpFRP<n>.lean     pieces p4ip_<i>_<k> of image i (states in range k), data
    P4IlFRP<n>.lean     cat4 [pieces of image i] = p4i_fR_qp_<i>   (kernel; list equality)
    P4EpFRP<n>.lean     pieces p4ep_<k> of q0 = P4_zero, data
    P4ElFRP<x>.lean     (cat4 [pieces of q0]).cx = (cat4 [p4Z_0, ..., p4Z_3]).cx   (kernel)
    P4MgFRP<k>.lean     sum4 [p4ip_0_k, ..., p4ip_32_k] = p4ep_k   (kernel; one merge piece)
    P4RFRP.lean         fR_qpV : modeC 0 (toV fR) qpV = q0V; fR_qp_latticeDP
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402
import p4_chunks  # noqa: E402

CTL = 'fR_qp'
BUDGET = 25000


def key(t):
    return (tuple(t[0]), tuple(t[1]))


def lit_vec(v):
    return sum(10 + len(o) for m, o, cs in v for x in cs if Fraction(x) != 0) + 40


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_p4ctl_fRqp.py`.  {body}\n-/\n'
            + g.NS_OPEN)


PROF = 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'


def pack(items, size):
    files, cur, acc = [], [], 0
    for it in items:
        n = size(it)
        if cur and acc + n > BUDGET:
            files.append(cur)
            cur, acc = [], 0
        cur.append(it)
        acc += n
    if cur:
        files.append(cur)
    return files


def split(v, bounds):
    """Pieces of the sorted term list v by the boundary states (piece k: bounds[k-1] <= s < bounds[k])."""
    pieces = [[] for _ in range(len(bounds) + 1)]
    for t in sorted(v, key=key):
        k = sum(1 for b in bounds if b <= key(t))
        pieces[k].append(t)
    return pieces


def main():
    K = int(sys.argv[1]) if len(sys.argv) > 1 else 12
    out = g.LEAN
    lines = (HERE / 'p4_controls' / f'{CTL}.jsonl').read_text().splitlines()
    recs = [json.loads(x) for x in lines[1:-1]]
    P4 = json.loads((HERE / 'p4.json').read_text())
    fields = {f['id']: f['vector'] for f in P4['fields']}
    subs = p4_chunks.control_subchunks(fields['P4_plus'], CTL, 75)
    q0 = sorted(fields['P4_zero'], key=key)
    step = (len(q0) + K - 1) // K
    bounds = [key(q0[i]) for i in range(step, len(q0), step)][:K - 1]
    K = len(bounds) + 1
    sname = lambda c, j: f'p4sP_{c}_{j}'  # noqa: E731

    # 1. sub-chunk links split by component (chunks 1..3; chunk 0 is built)
    for c in (1, 2, 3):
        js = [j for cc, j, _ in subs if cc == c]
        lst = ', '.join(sname(c, j) for j in js)
        for x in range(4):
            text = header(['P4Ctl', f'P4DataP{c}', 'P4SubP0', 'P4SubP1'],
                          f'Triplet `P4_plus`, chunk {c}, component c{x}: the sub-chunks add up to the data',
                          'Kernel check of one component of the link (normalization by `sort4`, zeros dropped).')
            text += PROF
            text += (f'\ntheorem p4sP_{c}_link_c{x} :\n    (nz4 (sort4 (toVec4Q [{lst}].flatten))).c{x} =\n'
                     f'      p4P_{c}.c{x} := by\n  decide +kernel\n')
            text += g.NS_CLOSE
            (out / f'P4SubLkP{c}{x}.lean').write_text(text)
        text = header(['P4Ctl2'] + [f'P4SubLkP{c}{x}' for x in range(4)],
                      f'Triplet `P4_plus`, chunk {c}: the sub-chunks add up to the data', 'Assembled by `vec4_ext`.')
        text += (f'\ntheorem p4sP_{c}_link :\n    nz4 (sort4 (toVec4Q [{lst}].flatten)) = p4P_{c} :=\n'
                 f'  vec4_ext p4sP_{c}_link_c0 p4sP_{c}_link_c1 p4sP_{c}_link_c2 p4sP_{c}_link_c3\n')
        text += g.NS_CLOSE
        (out / f'P4SubLkP{c}.lean').write_text(text)

    # 2. image pieces
    items = []
    for i, r in enumerate(recs):
        for k, piece in enumerate(split(r['image'], bounds)):
            items.append((i, k, piece))
    ipfiles = pack(items, lambda t: lit_vec(t[2]))
    ipfile_of = {}
    for n, group in enumerate(ipfiles):
        text = header(['QA'], f'Control `{CTL}`: pieces of the partial images, part {n}',
                      'Data: the terms of each image in each range of output states.')
        for i, k, piece in group:
            ipfile_of[(i, k)] = f'P4IpFRP{n}'
            text += f'\nnoncomputable def p4ip_{i}_{k} : Vec4 :=\n  {g.vec4(piece)}\n'
        text += g.NS_CLOSE
        (out / f'P4IpFRP{n}.lean').write_text(text)
    # image links, about 6 images per file
    img_lines = (HERE / '..' / '..' / 'HaagerupIzumi' / 'C8' / 'Lattice')
    imgfile_of = {}
    for f in sorted(out.glob('P4ImgFRP*.lean')):
        for line in f.read_text().splitlines():
            if line.startswith('noncomputable def p4i_fR_qp_'):
                imgfile_of[int(line.split()[2].rsplit('_', 1)[1])] = f.stem
    il_groups = [list(range(a, min(a + 6, len(recs)))) for a in range(0, len(recs), 6)]
    for n, group in enumerate(il_groups):
        imps = ['P4Ctl2'] + sorted({imgfile_of[i] for i in group} | {ipfile_of[(i, k)] for i in group for k in range(K)})
        text = header(imps, f'Control `{CTL}`: images are the concatenations of their pieces, part {n}', 'Kernel check.')
        text += PROF
        for i in group:
            text += (f'\ntheorem p4il_{i} : cat4 [{", ".join(f"p4ip_{i}_{k}" for k in range(K))}] = p4i_fR_qp_{i} := by\n'
                     '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4IlFRP{n}.lean').write_text(text)

    # 3. expected pieces (q0)
    eitems = list(enumerate(split(q0, bounds)))
    epfiles = pack(eitems, lambda t: lit_vec(t[1]))
    epfile_of = {}
    for n, group in enumerate(epfiles):
        text = header(['QA'], f'Control `{CTL}`: pieces of `q₀`, part {n}', 'Data: the terms of `P4_zero` in each range of states.')
        for k, piece in group:
            epfile_of[k] = f'P4EpFRP{n}'
            text += f'\nnoncomputable def p4ep_{k} : Vec4 :=\n  {g.vec4(piece)}\n'
        text += g.NS_CLOSE
        (out / f'P4EpFRP{n}.lean').write_text(text)
    eps = ', '.join(f'p4ep_{k}' for k in range(K))
    for x in range(4):
        imps = ['P4Ctl2'] + sorted(set(epfile_of.values())) + [f'P4DataZ{c}' for c in range(4)]
        text = header(imps, f'`q₀` is the concatenation of its pieces, component c{x}', 'Kernel check (list equality).')
        text += PROF
        text += (f'\ntheorem p4el_c{x} : (cat4 [{eps}]).c{x} = (cat4 [p4Z_0, p4Z_1, p4Z_2, p4Z_3]).c{x} := by\n'
                 '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4ElFRP{x}.lean').write_text(text)

    # 4. merge pieces
    for k in range(K):
        imps = ['P4Ctl2', epfile_of[k]] + sorted({ipfile_of[(i, k)] for i in range(len(recs))})
        text = header(imps, f'Control `{CTL}`: merge check, output range {k}',
                      'The pieces of the 33 partial images in this range add up to the piece of `q₀`.')
        text += PROF
        text += (f'\ntheorem p4mg_{k} :\n    sum4 [{", ".join(f"p4ip_{i}_{k}" for i in range(len(recs)))}] =\n'
                 f'      p4ep_{k} := by\n  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4MgFRP{k}.lean').write_text(text)

    # 5. assembly
    N = len(recs)
    imps = (['P4Link', 'P4Ctl2', 'P4SubLkP0'] + [f'P4SubLkP{c}' for c in (1, 2, 3)]
            + [f'P4ChkFRP{i:02d}' for i in range(N)] + [f'P4IlFRP{n}' for n in range(len(il_groups))]
            + [f'P4ElFRP{x}' for x in range(4)] + [f'P4MgFRP{k}' for k in range(K)])
    text = header(imps, 'Control `fR_qp`: `F_R(0) q₊ = q₀` for the actual triplet',
                  '`fR_qpV` from the per-sub-chunk checks `P4ChkFRP*` (`modeQRF`), the links `P4SubLkP*`, the '
                  'image pieces `P4IlFRP*`, the merge pieces `P4MgFRP*` and `P4ElFRP*`; hence the '
                  '`LowerCertificate` field `fR_qp` for `latticeDP`.  No hypotheses beyond `FLMInput`.')
    pairs = ', '.join(f'({sname(c, j)}, p4i_fR_qp_{i})' for i, (c, j, _) in enumerate(subs))
    text += f'\nnoncomputable def p4pairs_fR_qp : List (QVec × Vec4) :=\n  [{pairs}]\n'
    alt = ' | '.join(['rfl'] * N)
    checks = ', '.join(f'p4c_fR_qp_{i}' for i in range(N))
    links = ', '.join(f'toV4_eq_of_link p4sP_{c}_link' for c in range(4))
    ehave = '\n'.join(
        f'    have e{i} : toV4 p4i_fR_qp_{i} = {" + ".join(f"toV4 p4ip_{i}_{k}" for k in range(K))} := by\n'
        f'      rw [← p4il_{i}, toV4_cat4]\n      simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]\n      abel'
        for i in range(N))
    mhave = '\n'.join(
        f'    have m{k} : toV4 p4ep_{k} = {" + ".join(f"toV4 p4ip_{i}_{k}" for i in range(N))} := by\n'
        f'      rw [← p4mg_{k}, toV4_sum4]\n      simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]\n      abel'
        for k in range(K))
    text += f'''
theorem p4pairs_fR_qp_ok : ∀ p ∈ p4pairs_fR_qp,
    (∀ q ∈ p.1, Valid q.1) ∧ nz4 (sort4 (toVec4Q (modeQRF fR 0 p.1))) = p.2 := by
  intro p hp
  simp only [p4pairs_fR_qp, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with {alt}
  exacts [{checks}]

theorem q0V_pieces : q0V = {" + ".join(f"toV4 p4ep_{k}" for k in range(K))} := by
  have h : cat4 [{eps}] = cat4 [p4Z_0, p4Z_1, p4Z_2, p4Z_3] :=
    vec4_ext p4el_c0 p4el_c1 p4el_c2 p4el_c3
  have h2 := congrArg toV4 h
  rw [toV4_cat4, toV4_cat4] at h2
  simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero] at h2
  simp only [q0V, p4Z, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]
  rw [← h2]
  abel

/-- **`F_R(0) q₊ = q₀`** in `V`. -/
theorem fR_qpV : modeC 0 (toV fR) qpV = q0V := by
  have h := ctl_pairs fR fR_valid 0 p4pairs_fR_qp p4pairs_fR_qp_ok
  have hin : qpV = (p4pairs_fR_qp.map fun p => toVQ p.1).sum := by
    simp only [qpV, p4P, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    rw [{links}]
    simp only [p4pairs_fR_qp, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    abel
  have hout : (p4pairs_fR_qp.map fun p => toV4 p.2).sum = q0V := by
{ehave}
{mhave}
    simp only [p4pairs_fR_qp, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]
    rw [{", ".join(f"e{i}" for i in range(N))}, q0V_pieces, {", ".join(f"m{k}" for k in range(K))}]
    abel
  rw [hin, h, hout]

/-- **Control `fR_qp`** of `LowerCertificate` for the actual triplet: `F_R(0) q₊ = q₀`. -/
theorem fR_qp_latticeDP (hF : FLMInput) (S₃ : Submodule ℂ V) (hS₃ : S₃ ≤ gradeC 3) :
    (latticeVOA hF).mode 0 (latticeDP hF S₃ hS₃).fR (latticeDP hF S₃ hS₃).qp =
      (latticeDP hF S₃ hS₃).q0 :=
  fR_qpV

#print axioms fR_qp_latticeDP
'''
    text += g.NS_CLOSE
    (out / 'P4RFRP.lean').write_text(text)
    print(json.dumps({'pieces': K, 'ip_files': len(ipfiles), 'il_files': len(il_groups),
                      'ep_files': len(epfiles), 'merge_files': K,
                      'piece_states': [sum(len(p) for i, k, p in items if k == kk) for kk in range(K)]}))


if __name__ == '__main__':
    main()
