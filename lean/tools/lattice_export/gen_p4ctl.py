#!/usr/bin/env python3
"""Lean replay of a right-current control of the triplet from the exported partial results.

Pure text processing of p4.json and p4_controls/<control>.jsonl (export_p4_controls.py); the
chunking is p4_chunks.control_subchunks, so the sub-chunks match the export line by line.

    python3 lean/tools/lattice_export/gen_p4ctl.py <control> [<out dir>]

controls: fR_qp (F_R(0) q+ = q0), fR_q0 (F_R(0) q0 = q-), fR_qm (F_R(0) q- = 0),
eR_qp (E_R(0) q+ = 0).  Writes (namespace HaagerupIzumi.C8.LatticeVOA):
    P4Sub<F><k>.lean      sub-chunk inputs `p4s<F>_<c>_<j> : QVec` (shared by the controls on the
                          same field and sub-chunk size; rewritten identically)
    P4SubLk<F><c>.lean    `p4s<F>_<c>_link : nz4 (sort4 (toVec4Q [subs of c].flatten)) = p4<F>_<c>`
    P4Img<C><k>.lean      the exported images `p4i_<control>_<i> : Vec4`
    P4Chk<C><ii>.lean     `p4c_<control>_<i>`: canonical states of the sub-chunk and
                          `nz4 (sort4 (toVec4Q (modeQRF cur 0 sub))) = image` (kernel)
    P4Sum<C>.lean         `p4sum_<control> : sum4 images = sum4 expected` (or `= Vec4.zero`)
    P4R<C>.lean           the identity in V and the LowerCertificate field for latticeDP
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402
import p4_chunks  # noqa: E402

FIELD = {'P4_plus': 'P', 'P4_zero': 'Z', 'P4_minus': 'M'}
VNAME = {'P': 'qpV', 'Z': 'q0V', 'M': 'qmV'}
CTL = {  # control: (current Vec, Lean tag, LowerCertificate field, D-field of q, expected)
    'fR_qp': ('fR', 'FRP', 'fR_qp', 'qp', 'q0'),
    'fR_q0': ('fR', 'FRZ', 'fR_q0', 'q0', 'qm'),
    'fR_qm': ('fR', 'FRM', 'fR_qm', 'qm', None),
    'eR_qp': ('eR', 'ERP', 'eR_qp', 'qp', None),
}
BUDGET = 25000


def lit_vec(v):
    return sum(10 + len(o) for m, o, cs in v for x in cs if Fraction(x) != 0)


def qvec(terms):
    return '[' + ',\n    '.join(f'(decState {g.enc_state(m, o)}, {g.qa(cs)})' for m, o, cs in terms) + ']'


def pack(items, size):
    files, cur, acc = [], [], 0
    for it in items:
        n = size(it)
        if cur and acc + n > BUDGET:
            files.append(cur)
            cur, acc = [], 0
        cur.append(it)
        acc += n
    if cur:
        files.append(cur)
    return files


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_p4ctl.py`.  {body}\n-/\n' + g.NS_OPEN)


def main():
    ctl = sys.argv[1]
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else g.LEAN
    cur, C, field_name, qd, exp = CTL[ctl]
    lines = (HERE / 'p4_controls' / f'{ctl}.jsonl').read_text().splitlines()
    meta = json.loads(lines[0])
    recs = [json.loads(x) for x in lines[1:-1]]
    tail = json.loads(lines[-1])
    assert tail['matches_expected'] and meta['chunks'] == len(recs)
    P4 = json.loads((HERE / 'p4.json').read_text())
    fields = {f['id']: f['vector'] for f in P4['fields']}
    F = FIELD[meta['input']]
    subs = p4_chunks.control_subchunks(fields[meta['input']], ctl, meta['states_per_chunk'])
    assert len(subs) == len(recs)
    for (c, j, terms), r in zip(subs, recs):
        assert (r['data_chunk'], r['sub'], r['n_states']) == (c, j, len(terms))
        assert r['first'] == terms[0][:2] and r['last'] == terms[-1][:2]
    sname = lambda c, j: f'p4s{F}_{c}_{j}'  # noqa: E731

    # sub-chunk data (QVec)
    subfiles = pack(subs, lambda t: 20 * len(t[2]))
    subfile_of = {}
    for k, group in enumerate(subfiles):
        text = header(['QA'] if False else ['ModeQ'], f'Triplet `{meta["input"]}`: sub-chunk inputs, part {k}',
                      'Data (one `ℚ(√13, √-3)` coefficient per state), not hypotheses.')
        for c, j, terms in group:
            subfile_of[(c, j)] = f'P4Sub{F}{k}'
            text += f'\nnoncomputable def {sname(c, j)} : QVec :=\n  {qvec(terms)}\n'
        text += g.NS_CLOSE
        (out / f'P4Sub{F}{k}.lean').write_text(text)

    # links: sub-chunks of data chunk c add up to p4<F>_<c>
    nchunks = 1 + max(c for c, _, _ in subs)
    for c in range(nchunks):
        js = [j for cc, j, _ in subs if cc == c]
        imps = ['P4Ctl', f'P4Data{F}{c}'] + sorted({subfile_of[(c, j)] for j in js})
        text = header(imps, f'Triplet `{meta["input"]}`, chunk {c}: the sub-chunks add up to the data',
                      'Kernel check (normalization by `sort4`, zero coefficients dropped by `nz4`).')
        text += 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'
        text += (f'\ntheorem p4s{F}_{c}_link :\n    nz4 (sort4 (toVec4Q [{", ".join(sname(c, j) for j in js)}].flatten)) =\n'
                 f'      p4{F}_{c} := by\n  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4SubLk{F}{c}.lean').write_text(text)

    # images (Vec4)
    imgs = list(enumerate(recs))
    imgfiles = pack(imgs, lambda t: lit_vec(t[1]['image']) + 50)
    imgfile_of = {}
    for k, group in enumerate(imgfiles):
        text = header(['QA'], f'Control `{ctl}`: exported partial images, part {k}',
                      f'Data: the image of each sub-chunk under `{cur}_(0)`, from `p4_controls/{ctl}.jsonl` '
                      '(mode engine), checked in `P4Chk*`.')
        for i, r in group:
            imgfile_of[i] = f'P4Img{C}{k}'
            text += f'\nnoncomputable def p4i_{ctl}_{i} : Vec4 :=\n  {g.vec4(r["image"])}\n'
        text += g.NS_CLOSE
        (out / f'P4Img{C}{k}.lean').write_text(text)

    # per-sub-chunk checks
    for i, ((c, j, terms), r) in enumerate(zip(subs, recs)):
        imps = ['P4Ctl', 'Data', subfile_of[(c, j)], imgfile_of[i]]
        text = header(imps, f'Control `{ctl}`, sub-chunk {i} (chunk {c}, part {j})',
                      f'Kernel check of `{cur}_(0)` on the sub-chunk with `modeQRF` (`ModeHH.lean`).')
        text += 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'
        text += (f'\ntheorem p4c_{ctl}_{i} : (∀ q ∈ {sname(c, j)}, Valid q.1) ∧\n'
                 f'    nz4 (sort4 (toVec4Q (modeQRF {cur} 0 {sname(c, j)}))) = p4i_{ctl}_{i} := by\n'
                 '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'P4Chk{C}{i:02d}.lean').write_text(text)

    # merge check
    imps = ['P4Ctl'] + sorted(set(imgfile_of.values()))
    rhs = 'Vec4.zero'
    if exp:
        EF = {'q0': 'Z', 'qm': 'M'}[exp]
        imps += [f'P4Data{EF}{c}' for c in range(4)]
        rhs = f'sum4 [{", ".join(f"p4{EF}_{c}" for c in range(4))}]'
    text = header(imps, f'Control `{ctl}`: the partial images add up to the expected vector',
                  'Kernel check (balanced merging, `sum4`).')
    text += 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'
    text += (f'\ntheorem p4sum_{ctl} :\n    sum4 [{", ".join(f"p4i_{ctl}_{i}" for i in range(len(recs)))}] =\n'
             f'      {rhs} := by\n  decide +kernel\n')
    text += g.NS_CLOSE
    (out / f'P4Sum{C}.lean').write_text(text)

    # assembly
    imps = ['P4Link', f'P4Sum{C}'] + [f'P4SubLk{F}{c}' for c in range(nchunks)] + \
        [f'P4Chk{C}{i:02d}' for i in range(len(recs))]
    qv = VNAME[F]
    expV = {'q0': 'q0V', 'qm': 'qmV', None: '0'}[exp]
    dexp = {'q0': '(latticeDP hF S₃ hS₃).q0', 'qm': '(latticeDP hF S₃ hS₃).qm', None: '0'}[exp]
    text = header(imps, f'Control `{field_name}` for the actual triplet',
                  f'`{cur}_(0) {qv} = {expV}` from the per-sub-chunk checks `P4Chk{C}*`, the links '
                  f'`P4SubLk{F}*` and the merge check `P4Sum{C}` (`ctl_pairs`, `P4Ctl.lean`); hence the '
                  f'`LowerCertificate` field `{field_name}` for `latticeDP`.  No hypotheses beyond `FLMInput`.')
    pairs = ', '.join(f'({sname(c, j)}, p4i_{ctl}_{i})' for i, (c, j, _) in enumerate(subs))
    text += f'\nnoncomputable def p4pairs_{ctl} : List (QVec × Vec4) :=\n  [{pairs}]\n'
    alt = ' | '.join(['rfl'] * len(recs))
    checks = ', '.join(f'p4c_{ctl}_{i}' for i in range(len(recs)))
    links = ', '.join(f'toV4_eq_of_link p4s{F}_{c}_link' for c in range(nchunks))
    text += f'''
theorem p4pairs_{ctl}_ok : ∀ p ∈ p4pairs_{ctl},
    (∀ q ∈ p.1, Valid q.1) ∧ nz4 (sort4 (toVec4Q (modeQRF {cur} 0 p.1))) = p.2 := by
  intro p hp
  simp only [p4pairs_{ctl}, List.mem_cons, List.not_mem_nil, or_false] at hp
  rcases hp with {alt}
  exacts [{checks}]

theorem {ctl}V : modeC 0 (toV {cur}) {qv} = {expV} := by
  have h := ctl_pairs {cur} {cur}_valid 0 p4pairs_{ctl} p4pairs_{ctl}_ok
  have hin : {qv} = (p4pairs_{ctl}.map fun p => toVQ p.1).sum := by
    simp only [{qv}, p4{F}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    rw [{links}]
    simp only [p4pairs_{ctl}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
    abel
  have hout : (p4pairs_{ctl}.map fun p => toV4 p.2).sum = {expV} := by
    rw [show (p4pairs_{ctl}.map fun p => toV4 p.2) =
        [{", ".join(f"p4i_{ctl}_{i}" for i in range(len(recs)))}].map toV4 from rfl,
      ← toV4_sum4, p4sum_{ctl}]
    {"rw [toV4_sum4]" + chr(10) + "    rfl" if exp else "simp [toV4, Vec4.zero]"}
  rw [hin, h, hout]

/-- **Control `{field_name}`** for the actual triplet. -/
theorem {field_name}_latticeDP (hF : FLMInput) (S₃ : Submodule ℂ V) (hS₃ : S₃ ≤ gradeC 3) :
    (latticeVOA hF).mode 0 (latticeDP hF S₃ hS₃).{cur[0]}R (latticeDP hF S₃ hS₃).{qd} = {dexp} :=
  {ctl}V

#print axioms {field_name}_latticeDP
'''
    text += g.NS_CLOSE
    (out / f'P4R{C}.lean').write_text(text)
    print(json.dumps({'control': ctl, 'sub_files': len(subfiles), 'links': nchunks,
                      'img_files': len(imgfiles), 'checks': len(recs)}))


if __name__ == '__main__':
    main()
