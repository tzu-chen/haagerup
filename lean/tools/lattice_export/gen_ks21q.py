#!/usr/bin/env python3
"""Lean replay of the lower certificate K_(1) S2 <= K (LowerCertificate.KS₂1) with `modeQRF`.

Written 4 October 2026 (17:00); replaces the stopped `gen_lower_ks21.py` (Vec4.mode, 8.3 s for
H_R(1) r_61).  Probe (drafts/ks21/KS21Probe.lean, r_61, 72 terms): link 0.47 s, H_R 2.55 s,
H_L 2.2 s, E_R 0.71 s, E_L 0.10 s; peak 1.59 GiB.  Pure text processing of s2.json.

    python3 lean/tools/lattice_export/gen_ks21q.py [<out dir>]

Writes (namespace HaagerupIzumi.C8.LatticeVOA)
    KsQData<n>.lean   `s2q_k : QVec`, the basis vector r_k with one QA coefficient per state
    KsQLink<n>.lean   `s2q_link_k : (∀ q ∈ s2q_k, Valid q.1) ∧ nz4 (sort4 (toVec4Q s2q_k)) = s2r_k`
    KsQChk<nn>.lean   `ks21_<c>_<k> : kOK (nz4 (sort4 (toVec4Q (modeQRF <c> 1 s2q_k)))) = true`
    KS21.lean         `KS21_Kspan`, `KS21_latticeDP`
Check files are packed by estimated kernel time (ms per term of r_k, from the probe).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402
import gen_p4ctl as gc  # noqa: E402

CUR = [('hL', 0, 31.0), ('eL', 1, 2.0), ('fL', 2, 2.0), ('hR', 3, 36.0), ('eR', 4, 10.0), ('fR', 5, 10.0)]
LINK_MS = 7.0
BUDGET_MS = 4500
PROF = 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'


def pack(items, size, budget):
    files, cur, acc = [], [], 0
    for it in items:
        s = size(it)
        if cur and acc + s > budget:
            files.append(cur)
            cur, acc = [], 0
        cur.append(it)
        acc += s
    if cur:
        files.append(cur)
    return files


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_ks21q.py`.  {body}\n-/\n' + g.NS_OPEN)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else g.LEAN
    B = g.DATA['basis']
    n = len(B)
    files = {'data': [], 'link': [], 'chk': []}
    datafile = {}
    for d, group in enumerate(gc.pack(list(enumerate(B)), lambda t: 20 * len(t[1]))):
        text = header(['ModeQ'], f'The `S₂` basis with one `ℚ(√13, √-3)` coefficient per state, part {d}',
                      'Data: `s2q_k` is `r_k` of `S2Data` (checked in `KsQLink*`).')
        for k, v in group:
            datafile[k] = f'KsQData{d}'
            text += f'\nnoncomputable def s2q_{k} : QVec :=\n  {gc.qvec(v)}\n'
        text += g.NS_CLOSE
        (out / f'KsQData{d}.lean').write_text(text)
        files['data'].append(f'KsQData{d}')
    for d, group in enumerate(pack(list(range(n)), lambda k: LINK_MS * len(B[k]) + 20, BUDGET_MS)):
        text = header(['P4Ctl', 'S2Data'] + sorted({datafile[k] for k in group}),
                      f'The `QVec` basis vectors are the `Vec4` basis vectors, part {d}', 'Kernel checks.')
        text += PROF
        for k in group:
            text += (f'\ntheorem s2q_link_{k} : (∀ q ∈ s2q_{k}, Valid q.1) ∧ nz4 (sort4 (toVec4Q s2q_{k})) = s2r_{k} := by\n'
                     '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'KsQLink{d}.lean').write_text(text)
        files['link'].append(f'KsQLink{d}')
    items = [(k, c, i, ms) for k in range(n) for c, i, ms in CUR]
    for d, group in enumerate(pack(items, lambda t: t[3] * len(B[t[0]]) + 20, BUDGET_MS)):
        text = header(['P4Ctl', 'LatticeLowerCore'] + sorted({datafile[k] for k, _, _, _ in group}),
                      f'`K_(1) S₂ ⊆ K`: checks, part {d}',
                      'Kernel checks `x_(1) r_k ∈ K` for the six currents `x` (`modeQRF`, decomposition `kOK`).')
        text += PROF
        for k, c, _, _ in group:
            text += (f'\ntheorem ks21_{c}_{k} : kOK (nz4 (sort4 (toVec4Q (modeQRF {c} 1 s2q_{k})))) = true := by\n'
                     '  decide +kernel\n')
        text += g.NS_CLOSE
        (out / f'KsQChk{d:02d}.lean').write_text(text)
        files['chk'].append(f'KsQChk{d:02d}')

    imps = ['P4Link', 'S2Link'] + files['link'] + files['chk']
    text = header(imps, '`K_(1) S₂ ⊆ K` for the lattice VOA',
                  'From the kernel checks `KsQChk*` (`x_(1) r_k ∈ K` for the six currents and the 120 basis '
                  'vectors, `modeQRF` with the link `toVQ_modeQRF = modeC`) and the links `KsQLink*`, by '
                  'bilinearity over the spanning sets: `KS21_Kspan`, and the `LowerCertificate` field `KS₂1` '
                  'for `latticeDP` (`KS21_latticeDP`).  No hypotheses beyond `FLMInput` (only in `latticeDP`).')
    text += '''
theorem ks21_of_check {c : Vec} (hc : ∀ p ∈ c, Valid p.1) {q : QVec} {r : Vec4}
    (hq : (∀ x ∈ q, Valid x.1) ∧ nz4 (sort4 (toVec4Q q)) = r)
    (h : kOK (nz4 (sort4 (toVec4Q (modeQRF c 1 q)))) = true) :
    modeC 1 (toV c) (toV4 r) ∈ Kspan := by
  have h1 := toV4_mem_Kspan_of_kOK h
  rw [toV4_nz4, toV4_sort4, toV4_toVec4Q, toVQ_modeQRF 1 c q hc hq.1] at h1
  rw [← hq.2, toV4_nz4, toV4_sort4, toV4_toVec4Q]
  exact h1
'''
    for c, i, _ in CUR:
        alt = ' | '.join(['rfl'] * n)
        text += f'''
theorem ks21_{c}_basis : ∀ x ∈ s2basis, modeC 1 (toV {c}) (toV4 x) ∈ Kspan := by
  intro x hx
  simp only [s2basis, List.mem_cons, List.not_mem_nil, or_false] at hx
  rcases hx with {alt}
  exacts [{", ".join(f"ks21_of_check (fun p hp => (currents_basisStates {i} p hp).1) s2q_link_{k} ks21_{c}_{k}" for k in range(n))}]

theorem ks21_{c}_S2 : ∀ a ∈ S2span, modeC 1 (toV {c}) a ∈ Kspan := by
  have h : S2span ≤ Kspan.comap (modeC 1 (toV {c})) := by
    rw [S2span, Submodule.span_le]
    rintro _ ⟨k, rfl⟩
    exact ks21_{c}_basis _ (s2basis_getD_mem k)
  exact fun a ha => h ha
'''
    text += '''
/-- **`K_(1) S₂ ⊆ K`** on the Fock model. -/
theorem KS21_Kspan : ∀ x ∈ Kspan, ∀ a ∈ S2span, modeC 1 x a ∈ Kspan := by
  intro x hx a ha
  have h : Kspan ≤ Kspan.comap ((modeC 1).flip a) := by
    rw [Kspan, Submodule.span_le]
    rintro _ (rfl | rfl | rfl | rfl | rfl | rfl)
    · exact ks21_hL_S2 a ha
    · exact ks21_eL_S2 a ha
    · exact ks21_fL_S2 a ha
    · exact ks21_hR_S2 a ha
    · exact ks21_eR_S2 a ha
    · exact ks21_fR_S2 a ha
  exact h hx

/-- **Control `KS₂1`** of `LowerCertificate` for the actual closure data. -/
theorem KS21_latticeDP (hF : FLMInput) (S₃ : Submodule ℂ V) (hS₃ : S₃ ≤ gradeC 3) :
    ∀ x ∈ (latticeDP hF S₃ hS₃).K, ∀ a ∈ (latticeDP hF S₃ hS₃).S₂,
      (latticeVOA hF).mode 1 x a ∈ (latticeDP hF S₃ hS₃).K :=
  KS21_Kspan

#print axioms KS21_latticeDP
'''
    text += g.NS_CLOSE
    (out / 'KS21.lean').write_text(text)
    print(json.dumps({k: len(v) for k, v in files.items()}))


if __name__ == '__main__':
    main()
