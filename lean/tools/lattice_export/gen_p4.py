#!/usr/bin/env python3
"""Lean data for the weight-four triplet q+, q0, q- (P4) from p4.json (export_p4.py).

Pure text processing (json + fractions); no modes.

    python3 lean/tools/lattice_export/gen_p4.py [<chunks per field>]

writes, in lean/HaagerupIzumi/C8/Lattice/,
    P4Data<F><c>.lean   chunk c of field F (F = P plus, Z zero, M minus): `p4<F>_<c> : Vec4`,
                        the terms of the field whose states fall in the c-th block of the sorted
                        state list (each field has about 9,300 nonzero rational components, about
                        110,000 literals, so one field per file would take about 2 GiB to
                        elaborate; S2Data, about 60,000 literals, took 1.2 GiB);
    P4Defs.lean         the chunk lists `p4P`, `p4Z`, `p4M`;
    P4St<F><c>.lean     kernel checks, per chunk: every state is canonical of grade four, with
                        integer Cartan eigenvalues (H_L: 0, H_R: 2, 0, -2), each state checked
                        once (P4Eig.lean); the rational version exhausted 4 GiB (14:07 run);
and prints the literal counts.  The left-current checks P4EL<F><c>.lean, P4FL<F><c>.lean (with
component halves ...a, ...b for chunks of more than 640 states) were written by a shell loop of
the same pattern (4 October 2026); this script does not regenerate them.
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402  (encoding helpers only)
import p4_chunks  # noqa: E402  (the chunking spec)

P4 = json.loads((HERE / 'p4.json').read_text())
NAMES = {'P4_plus': 'P', 'P4_zero': 'Z', 'P4_minus': 'M'}
HR = {'P4_plus': 2, 'P4_zero': 0, 'P4_minus': -2}


def literals(v):
    n = 0
    for m, o, cs in v:
        for x in cs:
            if Fraction(x) != 0:
                n += 10 + len(o)
    return n


def chunks(v, k):
    """The data chunks of the shared spec (p4_chunks.data_chunks): k consecutive blocks of the
    sorted states, cuts moved forward to changes of momentum."""
    return p4_chunks.data_chunks(v, k)


def main():
    k = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    report = {}
    defs = []
    for f in P4['fields']:
        F = NAMES[f['id']]
        parts = chunks(f['vector'], k)
        names = []
        for c, part in enumerate(parts):
            name = f'p4{F}_{c}'
            names.append(name)
            text = g.HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.QA')
            text += f'''/-!
# Data of the weight-four triplet: `{f['id']}`, chunk {c}

Generated by `lean/tools/lattice_export/gen_p4.py` from `p4.json` (`export_p4.py`; record
`hi_cft_20260923_next_structure_p4_controls.json`, vectors file SHA-256
`{P4['source_sha256'].get('hi_cft_20260923_next_structure_p4_controls.vectors.json.gz', '?')}`).
Data, not hypotheses: the states of chunk {c} of the sorted state list of `{f['id']}`
(`{len(part)}` of `{len(f['vector'])}` states, `{literals(part)}` literals).
-/
'''
            text += g.NS_OPEN
            text += f'\n/-- `{f["id"]}`, chunk {c}. -/\nnoncomputable def {name} : Vec4 :=\n  {g.vec4(part)}\n'
            text += g.NS_CLOSE
            (g.LEAN / f'P4Data{F}{c}.lean').write_text(text)
            report[name] = literals(part)
        defs.append((f, F, names))
    imports = '\n'.join(f'public import HaagerupIzumi.C8.Lattice.P4Data{F}{c}'
                        for _, F, names in defs for c in range(len(names)))
    text = g.HEADER.format(imports=imports + '\npublic import HaagerupIzumi.C8.Lattice.Model')
    text += '''/-!
# The weight-four triplet `q₊, q₀, q₋` as vectors of the Fock model

Generated by `lean/tools/lattice_export/gen_p4.py`.  `p4P`, `p4Z`, `p4M`: the chunks of
`P4_plus`, `P4_zero`, `P4_minus` (`P4Data*.lean`); `qpV`, `q0V`, `qmV` the vectors of `V` (sums of
the chunks).
-/
'''
    text += g.NS_OPEN
    for f, F, names in defs:
        text += f'\n/-- The chunks of `{f["id"]}`. -/\nnoncomputable def p4{F} : List Vec4 := [{", ".join(names)}]\n'
    for f, F, names in defs:
        v = {'P': 'qpV', 'Z': 'q0V', 'M': 'qmV'}[F]
        text += f'\n/-- `{f["id"]}` in `V`. -/\nnoncomputable def {v} : V := (p4{F}.map toV4).sum\n'
    text += g.NS_CLOSE
    (g.LEAN / 'P4Defs.lean').write_text(text)
    for f, F, names in defs:
        ev = HR[f['id']]
        for c, name in enumerate(names):
            text = g.HEADER.format(imports=f'public import HaagerupIzumi.C8.Lattice.P4Data{F}{c}\n'
                                           'public import HaagerupIzumi.C8.Lattice.P4Eig')
            text += f'''/-!
# The triplet field `{f['id']}`, chunk {c}: canonical grade-four states, Cartan eigenvalues

Kernel check: every state of `{name}` is canonical of grade four with integer Cartan
eigenvalues `H_L ↦ 0`, `H_R ↦ {ev}` (`P4Good`, `P4Eig.lean`), each state checked once (on the
component `c1`, which carries every state of the triplet data; the other components are sorted
sublists of it, `subsetSorted`).  `{name}_good`: the consequence for all components.
-/
'''
            text += g.NS_OPEN
            text += 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'
            text += (f'\ntheorem {name}_check : (∀ p ∈ {name}.c1, P4Good ({ev}) p.1) ∧\n'
                     f'    subsetSorted ({name}.c0.map Prod.fst) ({name}.c1.map Prod.fst) = true ∧\n'
                     f'    subsetSorted ({name}.c2.map Prod.fst) ({name}.c1.map Prod.fst) = true ∧\n'
                     f'    subsetSorted ({name}.c3.map Prod.fst) ({name}.c1.map Prod.fst) = true := by\n'
                     '  decide +kernel\n\n'
                     f'theorem {name}_good : {name}.AllStates (P4Good ({ev})) :=\n'
                     f'  allStates_of_c1 {name}_check.1 {name}_check.2.1 {name}_check.2.2.1\n'
                     f'    {name}_check.2.2.2\n')
            text += g.NS_CLOSE
            (g.LEAN / f'P4St{F}{c}.lean').write_text(text)
    print(json.dumps(report))


if __name__ == '__main__':
    main()
