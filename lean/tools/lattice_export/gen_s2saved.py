#!/usr/bin/env python3
"""Lean replay of the equality of the saved S2 basis (checkpoint rows r2_*) with S2span.

Written 4 October 2026 (16:40).  Pure text processing and exact arithmetic over Q(s, t)
(s^2 = 13, t^2 = -3) with fractions; no lattice engine.

    python3 lean/tools/lattice_export/gen_s2saved.py [<rows2.json> [<out dir>]]

<rows2.json> (default: cut from s3.json by load_rows2): {'order2': [...], 'rows2': [...]} of s3.json (export_s3.py: the 120 grade-two
rows r2_* of the checkpoint hi_cft_20260923_next_grade4_checkpoint/checkpoint_000024, the basis
that the records L2_P4 (p4.json 'virasoro_controls'), S3 and the lower closure are keyed to).

Both bases are echelon (coefficient 1 at the least state, distinct least states), so each vector
of one basis is a combination of the other by elimination at the least states; the script checks
that the remainders vanish (both directions) and writes (namespace HaagerupIzumi.C8.LatticeVOA)
    S2SvData<n>.lean   `s2sv_<j> : Vec4`, the saved row r2_<j> (data)
    S2SvIn<n>.lean     `s2sv_eq_<j> : s2sv_<j> = combo [(c, s2r_k), ...]`     (kernel)
    S2SvOut<n>.lean    `s2r_eq_sv_<k> : s2r_<k> = combo [(c, s2sv_j), ...]`   (kernel)
    S2Saved.lean       `s2saved`, `S2savedSpan`, `S2savedSpan_eq : S2savedSpan = S2span`
Check files are packed by the right-hand-side size (about 1 ms of kernel time per term, the
S2 pilot cost model) to about BUDGET_TERMS terms each.
"""
import ast
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_s2 as g  # noqa: E402

BUDGET_TERMS = 2500
BUDGET_LIT = 25000
Z = (F(0),) * 4


def qa(cs):
    return tuple(F(x) for x in cs)


def mul(x, y):
    a, b, c, d = x
    e, f, gg, h = y
    return (a * e + 13 * b * f - 3 * c * gg - 39 * d * h,
            a * f + b * e - 3 * (c * h + d * gg),
            a * gg + c * e + 13 * (b * h + d * f),
            a * h + d * e + b * gg + c * f)


def todict(v):
    return {(tuple(m), tuple(o)): qa(cs) for m, o, cs in v}


def express(v, basis, pivs):
    rem, coeffs = dict(v), {}
    while rem:
        cand = [k for k, p in enumerate(pivs) if rem.get(p, Z) != Z]
        assert cand, 'not in the span'
        k = min(cand, key=lambda k: pivs[k])
        c = rem[pivs[k]]
        coeffs[k] = c
        for st, x in basis[k].items():
            y = tuple(p - q for p, q in zip(rem.get(st, Z), mul(c, x)))
            if y == Z:
                rem.pop(st, None)
            else:
                rem[st] = y
    return sorted(coeffs.items())


def qa_lit(c):
    return g.qa([str(x) for x in c])


def lits(v):
    return sum(10 + len(o) for m, o, cs in v for x in cs if F(x) != 0)


def pack(items, size, budget):
    files, cur, acc = [], [], 0
    for it in items:
        n = size(it)
        if cur and acc + n > budget:
            files.append(cur)
            cur, acc = [], 0
        cur.append(it)
        acc += n
    if cur:
        files.append(cur)
    return files


def header(imports, title, body):
    return (g.HEADER.format(imports='\n'.join(f'public import HaagerupIzumi.C8.Lattice.{i}' for i in imports))
            + f'/-!\n# {title}\n\nGenerated by `lean/tools/lattice_export/gen_s2saved.py`.  {body}\n-/\n'
            + g.NS_OPEN)


PROF = 'set_option profiler true\nset_option profiler.threshold 50\nset_option Elab.async false\n'


def load_rows2(path=None):
    """'order2', 'rows2' of s3.json (read with raw_decode, without parsing the 37 MB rest)."""
    if path:
        return json.loads(Path(path).read_text())
    text = (HERE / 's3.json').read_text()
    dec, res = json.JSONDecoder(), {}
    for key in ('order2', 'rows2'):
        i = text.index(f'"{key}":') + len(key) + 3
        while text[i] == ' ':
            i += 1
        res[key], _ = dec.raw_decode(text, i)
    return res


def main():
    R = load_rows2(sys.argv[1] if len(sys.argv) > 1 and sys.argv[1] != '-' else None)
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else g.LEAN
    order = R['order2']
    rows = R['rows2']
    assert [r['id'] for r in rows] == order and len(order) == 120
    vecs = [ast.literal_eval(r['vector']) if isinstance(r['vector'], str) else r['vector'] for r in rows]
    B = [todict(v) for v in g.DATA['basis']]
    S = [todict(v) for v in vecs]
    for v in vecs:  # the data are written sorted, as in S2Data
        assert [(tuple(m), tuple(o)) for m, o, _ in v] == sorted((tuple(m), tuple(o)) for m, o, _ in v)
    piv = [min(b) for b in B]
    spiv = [min(s) for s in S]
    assert all(B[k][piv[k]] == qa(['1', '0', '0', '0']) for k in range(120))
    assert all(S[j][spiv[j]] == qa(['1', '0', '0', '0']) for j in range(120))
    fwd = [express(s, B, piv) for s in S]   # saved row j in terms of r_k
    bwd = [express(b, S, spiv) for b in B]  # r_k in terms of saved rows
    files = []

    # data
    datafile = {}
    for n, group in enumerate(pack(list(enumerate(vecs)), lambda t: lits(t[1]) + 40, BUDGET_LIT)):
        text = header(['QA', 'Data'], f'The saved `S₂` basis (checkpoint rows `r2_*`), part {n}',
                      'Data: `s2sv_j` is the row `' + order[0][:3] + '<j>` of '
                      '`hi_cft_20260923_next_grade4_checkpoint/checkpoint_000024` (via `export_s3.py`).')
        for j, v in group:
            datafile[j] = f'S2SvData{n}'
            text += f'\n/-- Saved row `{order[j]}`. -/\nnoncomputable def s2sv_{j} : Vec4 :=\n  {g.vec4(v)}\n'
        text += g.NS_CLOSE
        (out / f'S2SvData{n}.lean').write_text(text)
        files.append(f'S2SvData{n}')

    def combo(coeffs, name):
        return 'combo [' + ', '.join(f'({qa_lit(c)}, {name}_{k})' for k, c in coeffs) + ']'

    # checks, direction 1 (saved rows in S2span)
    infiles = []
    items = list(enumerate(fwd))
    for n, group in enumerate(pack(items, lambda t: sum(len(B[k]) for k, _ in t[1]) + 20, BUDGET_TERMS)):
        imps = ['S2Data'] + sorted({datafile[j] for j, _ in group})
        text = header(imps, f'Saved `S₂` rows as combinations of the replayed basis, part {n}',
                      'Kernel checks `s2sv_j = ∑ c r_k`.')
        text += PROF
        for j, coeffs in group:
            text += f'\ntheorem s2sv_eq_{j} :\n    s2sv_{j} = {combo(coeffs, "s2r")} := by\n  decide +kernel\n'
        text += g.NS_CLOSE
        (out / f'S2SvIn{n}.lean').write_text(text)
        infiles.append(f'S2SvIn{n}')

    # checks, direction 2 (replayed basis in the saved span)
    outfiles = []
    items = list(enumerate(bwd))
    for n, group in enumerate(pack(items, lambda t: sum(len(S[j]) for j, _ in t[1]) + 20, BUDGET_TERMS)):
        imps = ['S2Data'] + sorted({datafile[j] for _, cs in group for j, _ in cs})
        text = header(imps, f'Replayed `S₂` basis as combinations of the saved rows, part {n}',
                      'Kernel checks `s2r_k = ∑ c s2sv_j`.')
        text += PROF
        for k, coeffs in group:
            text += f'\ntheorem s2r_eq_sv_{k} :\n    s2r_{k} = {combo(coeffs, "s2sv")} := by\n  decide +kernel\n'
        text += g.NS_CLOSE
        (out / f'S2SvOut{n}.lean').write_text(text)
        outfiles.append(f'S2SvOut{n}')

    # assembly
    def forall_list(coeffs, mem):
        s = 'fun _ h => absurd h List.not_mem_nil'
        for k, _ in reversed(coeffs):
            s = f'List.forall_mem_cons.2 ⟨{mem}_{k}, {s}⟩'
        return s

    imps = ['S2CloseMem'] + files + infiles + outfiles
    text = header(imps, 'The saved `S₂` basis spans `S2span`',
                  'The 120 checkpoint rows `r2_*` (`s2sv_j`, data) and the replayed echelon basis '
                  '`s2r_k` of `S2Data` express each other (`S2SvIn*`, `S2SvOut*`), so their spans in `V` '
                  'coincide: `S2savedSpan_eq`.  Records keyed to the saved basis (`L2_P₄`, `S₃`, the lower '
                  'closure) can therefore be imported against `S2span = (latticeD …).S₂`.')
    text += '\n/-- The saved rows, in the order `' + order[0] + '`, … , `' + order[-1] + '`. -/\n'
    text += 'noncomputable def s2saved : List Vec4 :=\n  [' + ', '.join(f's2sv_{j}' for j in range(120)) + ']\n'
    text += '''
theorem s2saved_length : s2saved.length = 120 := rfl

/-- The `j`-th saved row in `V`. -/
noncomputable def s2svec (j : Fin 120) : V := toV4 (s2saved.getD j.val Vec4.zero)

/-- The span of the saved rows. -/
noncomputable def S2savedSpan : Submodule ℂ V := Submodule.span ℂ (Set.range s2svec)

theorem s2saved_mem_span : ∀ x ∈ s2saved, toV4 x ∈ S2savedSpan := by
  intro x hx
  obtain ⟨j, hj, rfl⟩ := List.mem_iff_getElem.1 hx
  have hj' : j < 120 := by
    rw [← s2saved_length]
    exact hj
  apply Submodule.subset_span
  refine ⟨⟨j, hj'⟩, ?_⟩
  simp only [s2svec, List.getD_eq_getElem?_getD, List.getElem?_eq_getElem hj, Option.getD_some]
'''
    for j in range(120):
        text += f'\ntheorem s2sv_mem_{j} : s2sv_{j} ∈ s2saved := by simp [s2saved]\n'
    for j in range(120):
        text += (f'\ntheorem s2sv_mem_S2span_{j} : toV4 s2sv_{j} ∈ S2span :=\n'
                 f'  rel_mem_combo s2sv_eq_{j} ({forall_list(fwd[j], "s2r_mem")})\n')
    text += '''
theorem sv_mem_combo {src : Vec4} {cs : List (QA × Vec4)} (h : src = combo cs)
    (hcs : ∀ p ∈ cs, p.2 ∈ s2saved) : toV4 src ∈ S2savedSpan := by
  rw [h]
  exact toV4_combo_mem cs fun p hp => s2saved_mem_span _ (hcs p hp)
'''
    for k in range(120):
        text += (f'\ntheorem s2r_mem_saved_{k} : toV4 s2r_{k} ∈ S2savedSpan :=\n'
                 f'  sv_mem_combo s2r_eq_sv_{k} ({forall_list(bwd[k], "s2sv_mem")})\n')
    alt = ' | '.join(['rfl'] * 120)
    text += f'''
/-- Every saved row lies in `S2span`. -/
theorem s2saved_mem_S2span : ∀ x ∈ s2saved, toV4 x ∈ S2span := by
  intro x hx
  simp only [s2saved, List.mem_cons, List.not_mem_nil, or_false] at hx
  rcases hx with {alt}
  exacts [{", ".join(f"s2sv_mem_S2span_{j}" for j in range(120))}]

/-- Every vector of the replayed basis lies in the saved span. -/
theorem s2basis_mem_saved : ∀ x ∈ s2basis, toV4 x ∈ S2savedSpan := by
  intro x hx
  simp only [s2basis, List.mem_cons, List.not_mem_nil, or_false] at hx
  rcases hx with {alt}
  exacts [{", ".join(f"s2r_mem_saved_{k}" for k in range(120))}]

/-- **The saved `S₂` basis spans `S₂`.** -/
theorem S2savedSpan_eq : S2savedSpan = S2span := by
  apply le_antisymm
  · rw [S2savedSpan, Submodule.span_le]
    rintro _ ⟨j, rfl⟩
    exact s2saved_mem_S2span _ (s2saved_getD_mem j)
  · rw [S2span, Submodule.span_le]
    rintro _ ⟨k, rfl⟩
    exact s2basis_mem_saved _ (s2basis_getD_mem k)

/-- Membership in `S₂` from a combination of saved rows. -/
theorem toV4_combo_saved_mem (l : List (QA × Vec4)) (h : ∀ p ∈ l, p.2 ∈ s2saved) :
    toV4 (combo l) ∈ S2span := by
  rw [← S2savedSpan_eq]
  exact toV4_combo_mem l fun p hp => s2saved_mem_span _ (h p hp)

#print axioms S2savedSpan_eq
#print axioms toV4_combo_saved_mem
'''
    text += g.NS_CLOSE
    # s2saved_getD_mem must precede its use
    text = text.replace('theorem s2saved_mem_span :', '''theorem s2saved_getD_mem (j : Fin 120) : s2saved.getD j.val Vec4.zero ∈ s2saved := by
  have hj : j.val < s2saved.length := by
    rw [s2saved_length]
    exact j.2
  rw [List.getD_eq_getElem?_getD, List.getElem?_eq_getElem hj, Option.getD_some]
  exact List.getElem_mem hj

theorem s2saved_mem_span :''', 1)
    (out / 'S2Saved.lean').write_text(text)
    print(json.dumps({'data': files, 'in': infiles, 'out': outfiles,
                      'in_terms': [sum(len(B[k]) for k, _ in c) for c in fwd][:0],
                      'fwd_nnz': sum(map(len, fwd)), 'bwd_nnz': sum(map(len, bwd))}))


if __name__ == '__main__':
    main()
