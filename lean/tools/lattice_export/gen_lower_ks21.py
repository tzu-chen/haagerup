#!/usr/bin/env python3
"""Lean text for the lower certificate `K_(1) S₂ ⊆ K` (LowerCertificate.KS₂1) on the 120 echelon
vectors r_k of the minimal-generation record: `H_L(1) r_k ∈ K` and `H_R(1) r_k ∈ K`, each one
`decide +kernel` theorem `kOK (Vec4.mode (Vec4.ofVec h) 1 s2r_k) = true` (LatticeLowerCore.lean:
the kernel computes the mode and its decomposition along the six currents).  E_L, F_L, E_R, F_R
follow by the commutator formula (ProofMapLattice.lean), so only the Cartan currents are checked.

Pure text processing of s2.json (basis sizes, for packing); it computes no modes.

    python3 lean/tools/lattice_export/gen_lower_ks21.py probe <k> ...   # LatticeLowerProbe.lean
    python3 lean/tools/lattice_export/gen_lower_ks21.py all <ms per term> <budget ms per file>

`all` writes LatticeLowerH<NN>.lean (checks) and LatticeLowerH.lean (assembly over s2basis).

**Probe, 4 October 2026, 14:51 (job 145121-d94acc): stopped, not run in full.**  `probe 61 42`
(r_61: 72 terms, r_42: 32 terms): kernel 5.85 s (H_L r_61), 8.25 s (H_R r_61), 1.49 s, 1.75 s;
peak 3.1 GiB under a 4096 MiB reservation.  About 0.05-0.1 s per term of r_k per check, so the
240 checks need about 400-600 s of kernel time, and the heaviest single checks alone exceed a
1.4 GiB file estimate (0.45 GiB + 0.2 GiB/s).  Not cheap; the stop rule (> 2.5 GiB / 4096 MiB)
applied.  LatticeLowerCore.lean (kOK, its meaning, sanity check on the currents) is built.

**Superseded (17:05):** `KS₂1` is proved by the lattice agent with the faster `modeQRF`
(Lattice/KS21.lean, `KS21_latticeDP`: 720 checks, about 320 s of kernel time) and discharged in
`ProofMap.lattice_proof_map`.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[1] / 'HaagerupIzumi' / 'C8' / 'Lattice'
B = json.loads((HERE / 's2.json').read_text())['basis']
HEADER = 'module\n\n{imports}\n\n@[expose] public section\n'
NS_OPEN = '\nnamespace HaagerupIzumi.C8\nnamespace LatticeVOA\n'
NS_CLOSE = '\nend LatticeVOA\nend HaagerupIzumi.C8\n'
SIDES = [('L', 'hL'), ('R', 'hR')]


def check(side, cur, k):
    return (f'theorem lowH_{side}_{k} : kOK (Vec4.mode (Vec4.ofVec {cur}) 1 s2r_{k}) = true := by\n'
            f'  decide +kernel\n')


def file_text(title, doc, items):
    lines = [HEADER.format(imports='public import HaagerupIzumi.C8.Lattice.LatticeLowerCore')]
    lines.append(f'/-!\n# {title}\n\n{doc}\n-/\n')
    lines.append(NS_OPEN)
    lines.append('set_option profiler true\nset_option profiler.threshold 50\n'
                 'set_option Elab.async false\n')
    for side, cur, k in items:
        lines.append(check(side, cur, k))
    lines.append(NS_CLOSE)
    return '\n'.join(lines)


def probe(ks):
    items = [(s, c, k) for k in ks for s, c in SIDES]
    doc = ('Generated by `lean/tools/lattice_export/gen_lower_ks21.py probe`: timing probe of the\n'
           'checks `H(1) r_k ∈ K` for ' + ', '.join(f'r_{k} ({len(B[k])} terms)' for k in ks) + '.')
    (LEAN / 'LatticeLowerProbe.lean').write_text(file_text('Probe: `K_(1) S₂ ⊆ K`', doc, items))


def write_all(ms_per_term, budget):
    items = [(s, c, k) for k in range(len(B)) for s, c in SIDES]
    files, cur, acc = [], [], 0.0
    for it in items:
        c = ms_per_term * len(B[it[2]]) + 20
        if cur and acc + c > budget:
            files.append((cur, acc))
            cur, acc = [], 0.0
        cur.append(it)
        acc += c
    files.append((cur, acc))
    for n, (group, acc) in enumerate(files):
        doc = ('Generated by `lean/tools/lattice_export/gen_lower_ks21.py` from `s2.json`.  Each\n'
               '`lowH_X_k`: `H_X(1) r_k` (computed by the lattice modes) equals its decomposition\n'
               'along the six currents, so lies in `K` (`toV4_mem_Kspan_of_kOK`).  Estimated kernel\n'
               f'time: about {acc / 1000:.1f} s.  Assembled in `LatticeLowerH.lean`.')
        (LEAN / f'LatticeLowerH{n:02d}.lean').write_text(
            file_text(f'`K_(1) S₂ ⊆ K` on the basis, part {n}', doc, group))
    imports = ['public import HaagerupIzumi.C8.Lattice.S2Link']
    imports += [f'public import HaagerupIzumi.C8.Lattice.LatticeLowerH{n:02d}' for n in range(len(files))]
    lines = [HEADER.format(imports='\n'.join(imports))]
    lines.append('''/-!
# `H_L(1) S₂ ⊆ K` and `H_R(1) S₂ ⊆ K` (generated assembly)

Generated by `lean/tools/lattice_export/gen_lower_ks21.py`.  From the 240 kernel checks
`lowH_X_k` of `LatticeLowerH<NN>.lean`: `lowH_basis_X` (every `r_k` of `s2basis`) and
`hX_one_mem : ∀ w ∈ S2span, modeC 1 (toV h_X) w ∈ Kspan`.  Part of the lower certificate
`K_(1) S₂ ⊆ K` (`LowerCertificate.KS₂1`); the other currents follow by the commutator formula in
`ProofMapLattice.lean`.  No hypotheses.
-/
''')
    lines.append(NS_OPEN)
    alts = ' | '.join(['rfl'] * len(B))
    for side, cur in SIDES:
        names = ', '.join(f'lowH_{side}_{k}' for k in range(len(B)))
        lines.append(f'''theorem lowH_basis_{side} : ∀ x ∈ s2basis, kOK (Vec4.mode (Vec4.ofVec {cur}) 1 x) = true := by
  intro x hx
  simp only [s2basis, List.mem_cons, List.not_mem_nil, or_false] at hx
  rcases hx with {alts}
  exacts [{names}]

theorem {cur}_one_mem : ∀ w ∈ S2span, modeC 1 (toV {cur}) w ∈ Kspan := by
  intro w hw
  induction hw using Submodule.span_induction with
  | mem y hy =>
    obtain ⟨k, rfl⟩ := hy
    have h := toV4_mem_Kspan_of_kOK (lowH_basis_{side} _ (s2basis_getD_mem k))
    rwa [toV4_mode _ _ _ (ofVec_allStates {cur}_valid) (s2vec_allValid k), toV4_ofVec] at h
  | zero => simp
  | add y z _ _ hy hz =>
    rw [map_add]
    exact Kspan.add_mem hy hz
  | smul c y _ hy =>
    rw [map_smul]
    exact Kspan.smul_mem c hy
''')
    lines.append(f'#print axioms hL_one_mem\n#print axioms hR_one_mem\n')
    lines.append(NS_CLOSE)
    (LEAN / 'LatticeLowerH.lean').write_text('\n'.join(lines))
    ests = [round(a / 1000, 2) for _, a in files]
    print(json.dumps({'files': len(files), 'checks': len(items), 'total_est_s': round(sum(ests), 1),
                      'max_est_s': max(ests)}))


if __name__ == '__main__':
    if sys.argv[1] == 'probe':
        probe([int(x) for x in sys.argv[2:]])
    else:
        write_all(float(sys.argv[2]), float(sys.argv[3]))
