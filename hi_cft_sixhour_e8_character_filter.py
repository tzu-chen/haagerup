"""Grade-three and exact residual-charge summaries; coordinated guard only.

Level-one A1/A2/A3 use their root-lattice characters; B2 uses five
Majorana fermions with even parity. G2 at level one uses a conservative
grade-three lower bound, not an undocumented character coefficient.
"""
import argparse
from fractions import Fraction as F
from math import comb, lcm
from pathlib import Path
import json


def multiply(a, b):
    return [sum(a[i]*b[n-i] for i in range(n+1)) for n in range(4)]


def vacuum_factor(factor):
    typ = factor["letter"], factor["rank"]
    m, k = factor["dimension"], factor["level"]
    pbw2 = m*(m+3)//2
    pbw3 = m+m*m+comb(m+2, 3)
    d2 = {("A", 1): 5, ("A", 2): 27, ("A", 3): 84,
          ("B", 2): 35, ("C", 2): 35, ("G", 2): 77}[typ]
    d3 = {("A", 1): 7, ("A", 2): 64, ("A", 3): 300,
          ("B", 2): 84, ("C", 2): 84, ("G", 2): 273}[typ]
    if k >= 3:
        return [1, m, pbw2, pbw3], True
    if k == 2:
        return [1, m, pbw2, pbw3-d3], True
    exact = {("A", 1): [1, 3, 4, 7], ("A", 2): [1, 8, 17, 46],
             ("A", 3): [1, 15, 51, 172],
             ("B", 2): [1, 10, 30, 85], ("C", 2): [1, 10, 30, 85]}
    if typ in exact:
        return exact[typ], True
    # The grade-three ideal is generated by at most dim(g)*dim(2theta)
    # vectors. This yields a valid, possibly weak lower bound.
    return [1, m, pbw2-d2, max(0, pbw3-m*d2)], False


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--scan", type=Path, default=Path("hi_cft_sixhour_e8_subalgebra_results.json"))
    p.add_argument("--refined", type=Path, default=Path("hi_cft_sixhour_e8_subalgebra_refined_results.json"))
    p.add_argument("--output", type=Path, default=Path("hi_cft_sixhour_e8_character_results.json"))
    args = p.parse_args()
    scan = json.loads(args.scan.read_text())
    data = json.loads(args.refined.read_text())
    embeddings = {r["database_number"]: r for r in scan["all_semisimple_embeddings"]}
    rows = []
    for old in data["full_W1_refined_candidates"]:
        row = old.copy()
        n = row["semisimple_database_number"]
        factors = embeddings[n]["factors"] if n else []
        character, exact = [1, 0, 0, 0], True
        for f in factors:
            ch, flag = vacuum_factor(f)
            character = multiply(character, ch)
            exact = exact and flag
        for _ in range(row["abelian_rank"]):
            character = multiply(character, [1, 1, 2, 3])
        assert character[1] == row["W1_dimension"]
        assert character[2] == row["affine_vacuum_grade2"]
        if F(row["residual_c"]) > 0:
            character = multiply(character, [1, 0, 1, 1])
        target3 = 956 if row["W1_dimension"] == 6 else 1307
        row.update(current_and_residual_character_lower_bound_through3=character,
                   affine_grade3_exact=exact, proposed_W_grade3=target3,
                   passes_grade3_necessary_test=character[3] <= target3)
        row["passes_all_through_grade3"] = row["passes_all_current_necessary_tests"] and row["passes_grade3_necessary_test"]
        row["factor_description"] = " x ".join(f'{f["letter"]}{f["rank"]}_{f["level"]}' for f in factors)+f' + U1^{row["abelian_rank"]}'
        residual = F(row["residual_c"])
        field_excluded = False
        if row["passes_all_through_grade3"] and 0 <= residual < 1:
            # A deliberately nonminimal cyclotomic conductor containing
            # all affine quantum dimensions, from the Weyl sine product.
            conductor = 1
            for f in factors:
                typ = f["letter"], f["rank"]
                determinant = {("A", 1): 2, ("A", 2): 3, ("A", 3): 4,
                    ("B", 2): 2, ("C", 2): 2, ("G", 2): 1}[typ]
                lacing = 3 if f["letter"] == "G" else 2 if f["letter"] in "BC" else 1
                conductor = lcm(conductor, 2*determinant*lacing*(f["level"]+f["dual_coxeter"]))
            if residual:
                # The preceding unitary filter proves the discrete-series m.
                m = int(row["residual_Virasoro_class"].split("=")[1])
                conductor = lcm(conductor, 4*m*(m+1))
            field_excluded = conductor % 13 != 0
            row["quantum_dimension_field_containing_conductor"] = conductor
            row["quantum_dimension_field_exclusion_reason"] = (
                "Finite local extensions cannot enlarge the field of quantum dimensions; pointed lattice dimensions are1; sqrt13 has conductor13.")
        row["excluded_by_small_residual_quantum_dimension_field"] = field_excluded
        row["passes_all_including_small_residual_field"] = row["passes_all_through_grade3"] and not field_excluded
        rows.append(row)
    summaries = {}
    for dim in (6, 19):
        keep = [r for r in rows if r["W1_dimension"] == dim and r["passes_all_including_small_residual_field"]]
        values = sorted({F(r["residual_c"]) for r in keep})
        near = [q for q in values if F(3, 2) <= q <= F(5, 2)]
        non2 = sorted((q for q in values if q != 2), key=lambda q: (abs(q-2), q))
        summaries[str(dim)] = {"remaining_embedding_candidates": len(keep),
            "all_distinct_residual_c": list(map(str, values)),
            "residual_c_in_3over2_to_5over2": list(map(str, near)),
            "nearest_non2_residual_c": str(non2[0]) if non2 else None,
            "nearest_non2_distance": str(abs(non2[0]-2)) if non2 else None,
            "near2_rows": [r for r in keep if F(r["residual_c"]) in near]}
    result = {"candidate_rows": rows, "summaries": summaries,
              "scope": "Necessary character/rank/containment filters only; surviving rows are not Haagerup constructions. G2_1 grade3 is bounded conservatively."}
    args.output.write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps({"grade3_new_exclusions": sum(r["passes_all_current_necessary_tests"] and not r["passes_grade3_necessary_test"] for r in rows),
        "small_residual_field_exclusions": sum(r["excluded_by_small_residual_quantum_dimension_field"] for r in rows),
        "summary": {k: {a: b for a, b in s.items() if a != "near2_rows"} for k, s in summaries.items()},
        "output": str(args.output)}), flush=True)


if __name__ == "__main__":
    main()
